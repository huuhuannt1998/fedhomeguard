#!/usr/bin/env python3
"""ISJ-GP table tab:runs (round isj3 r1, 2026-11-07; review r1 issues 2, 9, 10; r2 issue 43:
seeds printed as contiguous ranges): every predeclared run the paper
reports, with its corpus and households, draws and seeds, the rows it evaluates, the median trivial floor of those rows,
the budgets it evaluates and where the paper uses it. One table, so that no number is read against the wrong row set:
the decoder runs evaluate the test rows left after the server set (the first 10% of each device's test rows) is
removed, the ceiling runs the whole test split.

Reads results/novelty/*.jsonl only (draw counts, seeds, floors and budget grids come from the rows). Writes
generated/tab_runs.tex (tabular body) and generated/tab_runs_numbers.json under out/ (or $FHG_OUT).

    python3 scripts/gen_isj_runs_table.py
"""
import hashlib, json, os
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results", "novelty")
OUT = os.environ.get("FHG_OUT") or os.path.join(ROOT, "out")  # artifact: writes out/generated, out/figures

# (name in the paper, corpus and households, file, rows evaluated, where used)
RUNS = [
    ("Ceiling set", "IoT-23", "device 1--3", "competence_ceiling_iot23_main", "test split", "4, 7, B"),
    ("IID control", "IoT-23", "IID", "competence_ceiling_iot23_iid", "test split", "7, C"),
    ("CIC ceiling", "CIC IoT-IDAD 2024", "device 1--3", "competence_ceiling_cic", "test split", "7"),
    ("Decoder set", "IoT-23", "device 1--3", "maxflow_decoder_iot23", "evaluation", "1, 7"),
    ("CIC decoder", "CIC IoT-IDAD 2024", "device 1--3", "maxflow_decoder_cic", "evaluation", "7"),
    ("N-BaIoT decoder", "N-BaIoT", "device 1--2", "maxflow_decoder_nbaiot", "evaluation", "7"),
    ("Anomaly votes", "IoT-23", "device 1--3", "anomaly_vote_primary", "test split", "B"),
]


def load(name):
    p = os.path.join(RES, name + ".jsonl")
    return [json.loads(l) for l in open(p) if l.strip()], hashlib.sha256(open(p, "rb").read()).hexdigest()


def seed_ranges(seeds):
    """Contiguous seed runs, e.g. [0,1,2,10,...,39] -> '0--2, 10--39' (review r2 issue 43)."""
    out, start, prev = [], seeds[0], seeds[0]
    for x in seeds[1:] + [None]:
        if x is not None and x == prev + 1:
            prev = x
            continue
        out.append(f"{start}" if start == prev else f"{start}--{prev}")
        if x is not None:
            start = prev = x
    return ", ".join(out)


def budgets(r):
    if "c" in r:                      # ceiling runs: budgets 0..max
        return max(int(k) for k in r["c"])
    if "by_m" in r:                   # decoder runs
        return max(int(k) for k in r["by_m"])
    if "P_grid" in r:                 # anomaly votes: beta grid of step 0.05 at N = 20
        return len(r["P_grid"]) - 1
    return None


def main():
    nums, lines = {"runs": [], "sources": {}}, []
    lines += ["% GENERATED by scripts/gen_isj_runs_table.py -- do not edit",
              "\\begin{tabular}{llllllll}", "\\toprule",
              "Run & Corpus & Households & Draws (seeds) & Rows & $\\tau_{\\mathrm{triv}}$ & Budgets & Sections \\\\",
              "\\midrule"]
    for label, corpus, hh, name, rows_eval, used in RUNS:
        R, h = load(name); nums["sources"][name] = h
        seeds = sorted(int(r["seed"]) for r in R)
        tau = float(np.median([r["tau"] for r in R]))
        mmax = budgets(R[0])
        nums["runs"].append(dict(run=label, file=name, n=len(R), seeds=seed_ranges(seeds), tau=tau,
                                 m_max=mmax, rows=rows_eval))
        lines.append(f"{label} & {corpus} & {hh} & {len(R)} ({seed_ranges(seeds)}) & {rows_eval} & {tau:.3f} & "
                     f"$m\\le {mmax}$ & {used} \\\\")
    # the certified anomaly-based ensemble: three corpora, 30 draws each, no floor (it reports certified detection)
    seeds_all, per_corpus = [], []
    for name in ("certified_anomaly_nbaiot", "certified_anomaly_cic", "certified_anomaly_iot23"):
        R, h = load(name); nums["sources"][name] = h
        seeds_all += [int(r["seed"]) for r in R]
        per_corpus.append(seed_ranges(sorted(int(r["seed"]) for r in R)))
    if len(set(per_corpus)) != 1:
        raise SystemExit(f"anomaly-ensemble seeds differ by corpus: {per_corpus}")
    mm = max(int(k) for k in R[0]["by_m"])
    nums["runs"].append(dict(run="Certified anomaly ensemble", n_per_corpus=30, seeds=per_corpus[0], m_max=mm))
    lines.append(f"Anomaly ensemble & three corpora & device 1--3$^{{a}}$ & $3\\times 30$ ({per_corpus[0]}) & "
                 f"test split & -- & $m\\le {mm}$ & B \\\\")
    lines += ["\\bottomrule",
              "\\multicolumn{8}{@{}l}{$^{a}$ 1--2 device types per household on N-BaIoT, 1--3 on CIC IoT-IDAD 2024 and IoT-23.} \\\\",
              "\\end{tabular}"]
    os.makedirs(os.path.join(OUT, "generated"), exist_ok=True)
    open(os.path.join(OUT, "generated", "tab_runs.tex"), "w").write("\n".join(lines) + "\n")
    json.dump(nums, open(os.path.join(OUT, "generated", "tab_runs_numbers.json"), "w"), indent=1)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
