#!/usr/bin/env python3
"""ISJ-GP table tab:decoder (round isj2a plan, O-001@5): the max-flow certified decoder against plurality, abstention
and the oracle ceiling at m = 4 (20% malicious clients), per corpus and server-set size, plus certified precision at a
1% attack prior on IoT-23. Predeclarations: maxflow_decoder_2026-11-03.md and decoder_followup_2026-11-03.md.

Reads results/novelty/maxflow_decoder_*.jsonl only. Writes generated/tab_decoder.tex (tabular body) and
generated/tab_decoder_numbers.json in the ISJ-GP folder.

    python3 scripts/gen_isj_decoder_table.py
"""
import hashlib, json, os
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results", "novelty")
OUT = os.environ.get("FHG_OUT") or os.path.join(ROOT, "out")  # artifact: writes out/generated, out/figures
ROWS = [("IoT-23", "10\\%", "maxflow_decoder_iot23"), ("IoT-23", "2\\%", "maxflow_decoder_iot23_frac0.02"),
        ("IoT-23", "1\\%", "maxflow_decoder_iot23_frac0.01"), ("IoT-23", "0.5\\%", "maxflow_decoder_iot23_frac0.005"),
        ("N-BaIoT", "10\\%", "maxflow_decoder_nbaiot"), ("CIC IoT-IDAD 2024", "10\\%", "maxflow_decoder_cic")]
PRIOR = "maxflow_decoder_iot23_r3"


def load(name):
    p = os.path.join(RES, name + ".jsonl")
    return [json.loads(l) for l in open(p) if l.strip()], hashlib.sha256(open(p, "rb").read()).hexdigest()


def prec(r, a, m="4", prior=0.01):
    b = r["by_m"][m]; tp = b["cTPR_" + a]; fp = 1 - b["cBEN_" + a]
    return prior * tp / max(1e-12, prior * tp + (1 - prior) * fp)


PERCLASS = [("IoT-23", "10\\%", "maxflow_decoder_iot23_r3"), ("IoT-23", "1\\%", "maxflow_decoder_iot23_frac0.01"),
            ("IoT-23", "0.5\\%", "maxflow_decoder_iot23_frac0.005"), ("N-BaIoT", "10\\%", "maxflow_decoder_nbaiot")]


def main():
    # round isj3 r1 (2026-11-07), review r1 issues 20, 21, 27: collapses of all four rules; the server set's size in
    # labeled rows; four decimals where values sit near 1 (N-BaIoT); a second panel with the per-class rates
    # (certified detection, benign certified rate) of the runs that recorded them; the 1% prior note now gives the
    # re-weighted certified accuracy of every rule beside the certified-precision lower bound. Same result rows.
    nums, lines = {"rows": [], "perclass": [], "sources": {}}, []
    lines += ["% GENERATED by scripts/gen_isj_decoder_table.py -- do not edit",
              "\\begin{tabular}{llrcccccc}", "\\toprule",
              "\\multicolumn{9}{@{}l}{(a) Certified accuracy at $m=4$ ($\\beta=0.20$), median over draws, and collapses} \\\\",
              "\\midrule",
              "Corpus & Server set (rows) & Draws & $\\tau_{\\mathrm{triv}}$ & Plurality & Abstention & Decoder & Ceiling "
              "& Collapses P\\,/\\,A\\,/\\,D\\,/\\,C \\\\", "\\midrule"]
    for corpus, frac, name in ROWS:
        R, h = load(name); nums["sources"][name] = h
        med = lambda k: float(np.median([r["by_m"]["4"][k] for r in R]))
        tau = float(np.median([r["tau"] for r in R]))
        ns = int(np.median([r["n_server"] for r in R]))
        col = {a: sum(r["by_m"]["4"]["CA_" + a] <= r["tau"] for r in R) for a in ("P", "A", "D", "MAX")}
        row = dict(corpus=corpus, server=frac.replace("\\", ""), n_server=ns, n=len(R), tau=tau, P=med("CA_P"),
                   A=med("CA_A"), D=med("CA_D"), MAX=med("CA_MAX"), collapse_P=col["P"], collapse_A=col["A"],
                   collapse_D=col["D"], collapse_MAX=col["MAX"])
        nums["rows"].append(row)
        d = 4 if corpus == "N-BaIoT" else 3
        lines.append(f"{corpus} & {frac} ({ns:,}) & {len(R)} & {tau:.{d}f} & {row['P']:.{d}f} & {row['A']:.{d}f} & "
                     f"{row['D']:.{d}f} & {row['MAX']:.{d}f} & {col['P']}\\,/\\,{col['A']}\\,/\\,{col['D']}\\,/\\,{col['MAX']} \\\\")
    lines += ["\\midrule",
              "\\multicolumn{9}{@{}l}{(b) Per-class certified rates at $m=4$, median over draws, plurality\\,/\\,abstention\\,/\\,decoder} \\\\",
              "\\midrule",
              "Corpus & Server set & Draws & & \\multicolumn{2}{c}{Certified detection} & \\multicolumn{3}{c}{Benign certified rate} \\\\",
              "\\midrule"]
    for corpus, frac, name in PERCLASS:
        R, h = load(name); nums["sources"][name] = h
        d = 4 if corpus == "N-BaIoT" else 3
        det = {a: float(np.median([r["by_m"]["4"]["cTPR_" + a] for r in R])) for a in "PAD"}
        ben = {a: float(np.median([r["by_m"]["4"]["cBEN_" + a] for r in R])) for a in "PAD"}
        none = sum(r["by_m"]["4"]["cTPR_P"] == 0 for r in R)
        nums["perclass"].append(dict(corpus=corpus, server=frac.replace("\\", ""), n=len(R), det=det, ben=ben,
                                     plurality_no_attack_certified=none))
        lines.append(f"{corpus} & {frac} & {len(R)} & & \\multicolumn{{2}}{{c}}{{{det['P']:.{d}f}\\,/\\,{det['A']:.{d}f}\\,/\\,"
                     f"{det['D']:.{d}f}}} & \\multicolumn{{3}}{{c}}{{{ben['P']:.{d}f}\\,/\\,{ben['A']:.{d}f}\\,/\\,{ben['D']:.{d}f}}} \\\\")
    R, h = load(PRIOR); nums["sources"][PRIOR] = h
    pm = {a: float(np.median([prec(r, a) for r in R])) for a in "PAD"}
    rw = {a: float(np.median([0.01 * r["by_m"]["4"]["cTPR_" + a] + 0.99 * r["by_m"]["4"]["cBEN_" + a] for r in R]))
          for a in "PAD"}
    d_gt_p = sum(prec(r, "D") > prec(r, "P") for r in R)
    nums["prior_1pct"] = dict(n=len(R), precision_median=pm, reweighted_ca_median=rw, decoder_above_plurality=d_gt_p)
    lines += ["\\midrule",
              # round isj4 (2026-11-04): wrapped at about the table's natural width, so the float is not shrunk.
              f"\\multicolumn{{9}}{{@{{}}p{{1.24\\textwidth}}@{{}}}}{{(c) IoT-23, 1\\% attack prior, $m=4$, median of {len(R)} draws: "
              f"re-weighted certified accuracy plurality {rw['P']:.3f}, abstention {rw['A']:.3f}, decoder {rw['D']:.3f}, against "
              f"0.990 for always predicting benign; lower bound on certified precision plurality {pm['P']:.3f}, abstention "
              f"{pm['A']:.3f}, decoder {pm['D']:.3f} (decoder above plurality on {d_gt_p} of {len(R)}).}} \\\\",
              "\\bottomrule", "\\end{tabular}"]
    os.makedirs(os.path.join(OUT, "generated"), exist_ok=True)
    open(os.path.join(OUT, "generated", "tab_decoder.tex"), "w").write("\n".join(lines) + "\n")
    json.dump(nums, open(os.path.join(OUT, "generated", "tab_decoder_numbers.json"), "w"), indent=1)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
