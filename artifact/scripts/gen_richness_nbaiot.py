#!/usr/bin/env python3
"""Score the predeclared N-BaIoT richness test (predeclarations/richness_nbaiot.md).

The paper attributes the device-derived collapse to device identity predicting the
label. If that is the mechanism, richness is irrelevant where the coupling is
absent. Thresholds were fixed before the runs:

  P1  span of beta* across richness levels <= 0.05 (one grid step) on N-BaIoT
  P2  no level collapses on a majority of draws at beta = 0.20
  P3  the same grid on IoT-23 spans 0.000 to 0.450

This script reports each as PASS/FAIL against those numbers. It does not choose
them.
"""
import glob, json, os, statistics as st, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bstar import bstar

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
P1_SPAN, P2_COLLAPSE = 0.05, 0.50
NB = [("1", "e21_nbrich_1_1"), ("1--3", "e21_nbrich_1_3"), ("2--5", "e21_nbrich_2_5"),
      ("3--8", "e21_nbrich_3_8"), ("5--9", "e21_nbrich_5_9")]
IO = [("1", "e11b_dph1_1"), ("1--3", "e11b_dph1_3"), ("2--5", "e11b_dph2_5"),
      ("3--8", "e11b_dph3_8"), ("5--10", "e11b_dph5_10")]


def arm(stem):
    f = f"results/canonical/{stem}.jsonl"
    if not os.path.exists(f):
        return None
    rs = [x for x in (json.loads(l) for l in open(f) if l.startswith("{"))
          if x["partition_type"] == "device_derived" and x["k"] == 1]
    if not rs:
        return None
    b, _, n, _ = bstar(rs)
    tau = rs[0]["tau_triv"]
    b20 = [x for x in rs if abs(x["beta"] - 0.20) < 1e-9]
    coll = sum(1 for x in b20 if x["CA"] <= tau) / len(b20) if b20 else float("nan")
    return dict(bstar=b, n=n, collapse=coll,
                sjs=st.median([x["S_JS"] for x in rs]))


def table(rows, name):
    print(f"  {name}")
    print(f"    {'devices':<9}{'S_JS':>8}{'beta*':>8}{'collapse@0.20':>15}{'draws':>7}")
    got = {}
    for lab, stem in rows:
        a = arm(stem)
        if a is None:
            print(f"    {lab:<9}{'  (not run)':>38}"); continue
        got[lab] = a
        print(f"    {lab:<9}{a['sjs']:>8.3f}{a['bstar']:>8.3f}{a['collapse']:>15.2f}{a['n']:>7}")
    return got


nb = table(NB, "N-BaIoT (device identity carries no label information)")
print()
io = table(IO, "IoT-23 (device identity predicts the label)")
if not nb:
    raise SystemExit("\n  N-BaIoT arms not complete yet")

nb_span = max(a["bstar"] for a in nb.values()) - min(a["bstar"] for a in nb.values())
io_span = max(a["bstar"] for a in io.values()) - min(a["bstar"] for a in io.values())
p1 = nb_span <= P1_SPAN + 1e-9
p2 = all(a["collapse"] <= P2_COLLAPSE for a in nb.values())
p3 = io_span >= 0.40
print(f"\n  PREDECLARED SCORING")
print(f"    P1  N-BaIoT beta* span {nb_span:.3f} <= {P1_SPAN}        {'PASS' if p1 else 'FAIL'}")
print(f"    P2  no N-BaIoT level collapses on a majority   {'PASS' if p2 else 'FAIL'}")
print(f"    P3  IoT-23 span {io_span:.3f} across the same grid  {'PASS' if p3 else 'FAIL'}")
print(f"    -> mechanism prediction {'CONFIRMED' if (p1 and p2 and p3) else 'NOT confirmed'}")

mac = [f"\\newcommand{{\\nbrSpan}}{{{nb_span:.3f}}}",
       f"\\newcommand{{\\ioSpan}}{{{io_span:.3f}}}",
       f"\\newcommand{{\\nbrMin}}{{{min(a['bstar'] for a in nb.values()):.3f}}}",
       f"\\newcommand{{\\nbrMax}}{{{max(a['bstar'] for a in nb.values()):.3f}}}",
       f"\\newcommand{{\\nbrLevels}}{{{len(nb)}}}",
       f"\\newcommand{{\\nbrDraws}}{{{max(a['n'] for a in nb.values())}}}",
       f"\\newcommand{{\\nbrMaxCollapse}}{{{max(a['collapse'] for a in nb.values()):.2f}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/nbrich_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_richness_nbaiot.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  -> {OUT}/nbrich_macros.tex")

# the matched-skew cell the prose leans on
_one = arm("e21_nbrich_1_1")
if _one is not None:
    import re as _re
    _f = f"{OUT}/nbrich_macros.tex"
    _t = open(_f).read().rstrip("\n")
    _rs = [x for x in (json.loads(l) for l in
                       open("results/canonical/e21_nbrich_1_1.jsonl") if l.startswith("{"))
           if x["partition_type"] == "device_derived" and x["k"] == 1]
    _t += (f"\n\\newcommand{{\\nbrSjsOne}}{{{_one['sjs']:.3f}}}"
           f"\n\\newcommand{{\\nbrMargOne}}{{{st.median([x['mean_vote_margin'] for x in _rs]):.3f}}}\n")
    open(_f, "w").write(_t)
    print(f"  matched-cell macros: S_JS {_one['sjs']:.3f}, "
          f"margin {st.median([x['mean_vote_margin'] for x in _rs]):.3f}")
