#!/usr/bin/env python3
"""Class-balanced local loss at k=1 (review Question 2).

Under device-derived partitioning a household can hold 97% one class, and
unweighted cross-entropy then drives its member toward a near-constant
predictor -- which would be a training choice, not a property of the data. The
review asks whether the competence collapse survives the obvious fix. It does:
the margin moves in the fourth decimal and the breakdown point does not move.

Matched comparison -- the same three partition draws, the same seeds, the same
grid -- so the two numbers are comparable to each other even though three draws
is too few for an absolute beta*.
"""
import glob, json, os, statistics as st, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bstar import bstar
from aggregate import src as _src   # review r6: corrected same-predictor rows

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)


def load(pat, k=1, part="device_derived"):
    r = []
    for f in glob.glob(pat):
        r += [x for x in (json.loads(l) for l in open(f) if l.startswith("{"))
              if x["partition_type"] == part and x["k"] == k]
    return r


cb = load("results/canonical/e2cb_device_derived.jsonl")
base = load(_src("e2_device_derived_*.jsonl"))
seeds = sorted({r["partition_seed"] for r in cb} & {r["partition_seed"] for r in base})
cb = [r for r in cb if r["partition_seed"] in seeds]
base = [r for r in base if r["partition_seed"] in seeds]
mcb = st.median([r["mean_vote_margin"] for r in cb])
mba = st.median([r["mean_vote_margin"] for r in base])
bcb, _, _, _ = bstar(cb)
bba, _, _, _ = bstar(base)
mac = [f"\\newcommand{{\\cbMargin}}{{{mcb:.4f}}}",
       f"\\newcommand{{\\cbMarginBase}}{{{mba:.4f}}}",
       # r7 item 5: the difference of the two PRINTED (rounded) arms, the Table 5 rule,
       # so a reader subtracting the printed margins gets the printed delta
       f"\\newcommand{{\\cbDelta}}{{{round(float(f'{mcb:.4f}') - float(f'{mba:.4f}'), 4) + 0.0:+.4f}}}",
       f"\\newcommand{{\\cbDraws}}{{{len(seeds)}}}",
       f"\\newcommand{{\\cbSameBstar}}{{{'yes' if abs(bcb-bba) < 1e-9 else 'no'}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/cbalance_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_cbalance.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  matched on {len(seeds)} draws: margin {mba:.4f} -> {mcb:.4f} ({mcb-mba:+.4f}), "
      f"beta* {bba:.3f} -> {bcb:.3f}")
