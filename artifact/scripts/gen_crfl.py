#!/usr/bin/env python3
"""CRFL-style smoothing certificate: macros for the second-family comparison (W6/E3).

The review asked whether the OTHER certification family survives device-derived
skew. It does not reach this operating point at all, and for a reason that has
nothing to do with skew:

  the adversary's reach  Delta = 2*m*rho/N = 2*beta*rho   (m = beta*N, so N cancels)
  the achievable radius  R = sigma * Phi^{-1}(p_A),  which PEAKS in sigma

R peaks because noise buys radius but destroys the vote agreement that p_A
measures. Certifying one malicious client needs R > 2*beta*rho, and the only way
to shrink the right side is to clip harder -- which collapses the predictor to a
constant. Both directions are measured here rather than argued.
"""
import glob, json, os, statistics as st

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
peak = [json.loads(l) for l in open("results/canonical/e18_crfl_peak_dev.jsonl")
        if l.startswith("{")]
rho_rows = [json.loads(l) for l in open("results/canonical/e18_crfl_rho.jsonl")
            if l.startswith("{")]
tau = peak[0]["tau_triv"]

best = max(peak, key=lambda r: r["max_radius"])
# the working operating point: largest radius whose smoothed model still beats trivial
working = max([r for r in peak if r["smoothed_acc"] > tau],
              key=lambda r: r["max_radius"])
reach1 = 2.0 * 1 * working["rho"] / working["N"]
# the clipped-hard arm: does anything at rho small enough to certify m=1 still work?
hard = [r for r in rho_rows if r["beta"] == 0.0 and 0.1 * r["rho"] <= best["max_radius"] * 1.05]
hard_acc = min(r["smoothed_acc"] for r in hard) if hard else None

mac = [f"\\newcommand{{\\crflSigma}}{{{working['sigma']}}}",
       f"\\newcommand{{\\crflRho}}{{{working['rho']:.0f}}}",
       f"\\newcommand{{\\crflAcc}}{{{working['smoothed_acc']:.4f}}}",
       f"\\newcommand{{\\crflRadius}}{{{best['max_radius']:.4f}}}",
       f"\\newcommand{{\\crflReachOne}}{{{reach1:.2f}}}",
       f"\\newcommand{{\\crflRatio}}{{{reach1/best['max_radius']:.1f}}}",
       f"\\newcommand{{\\crflNsmooth}}{{{working['n_smooth']}}}"]
if hard_acc is not None:
    mac += [f"\\newcommand{{\\crflHardRho}}{{{max(r['rho'] for r in hard):.1f}}}",
            f"\\newcommand{{\\crflHardAcc}}{{{hard_acc:.4f}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/crfl_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_crfl.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  best achievable radius {best['max_radius']:.4f} at sigma={best['sigma']} "
      f"(radius peaks: it falls at both smaller and larger sigma)")
print(f"  working point rho={working['rho']:.0f} sigma={working['sigma']}: "
      f"smoothed acc {working['smoothed_acc']:.4f} > tau {tau:.4f}")
print(f"  reach of ONE malicious client 2*rho/N = {reach1:.2f}, "
      f"which is {reach1/best['max_radius']:.1f}x the achievable radius")
if hard_acc is not None:
    print(f"  clipping hard enough to certify m=1 (rho<= {max(r['rho'] for r in hard):.1f}) "
          f"gives smoothed acc {hard_acc:.4f} against tau {tau:.4f}")
