#!/usr/bin/env python3
"""Federation-size table, rebuilt so it cannot contradict Table 1 (W9d / E10 / Q5).

The old table reported beta*=0.100 for device-derived at N=20 while the ceiling
table reported 0.050 for the same quantity, and its IID column was right-censored
by a grid stopping at 0.40. Two causes, both fixed here: the N=20 row now comes
from the SAME 30-draw arm the ceiling table uses, so the two cannot disagree by
construction, and N=10/50 are re-run on the fine grid to 0.50.

Every beta* uses scripts/bstar.py. Draw counts are printed in the table, because
they differ by row and the review was right that a reader cannot otherwise tell
whether two numbers are the same quantity.
"""
import glob, json, os, statistics as st, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bstar import bstar

OUT = "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated"
ARMS = [(10, "results/canonical/e10b_N10_%s.jsonl"),
        (20, "results/canonical/e5f_*.jsonl"),
        (50, "results/canonical/e10b_N50_%s.jsonl")]


def load(pat, part, k=1):
    p = pat % part if "%s" in pat else pat
    r = []
    for f in glob.glob(p):
        r += [x for x in (json.loads(l) for l in open(f) if l.startswith("{"))
              if x["partition_type"] == part and x["k"] == k]
    return r


rows = ["% GENERATED by scripts/gen_fedsize.py -- do not edit",
        "\\begin{tabular}{lrrcccc}", "\\toprule",
        "Partition & $N$ & draws & $S_{\\mathrm{JS}}$ & margin & ens.\\ acc & "
        "$\\beta^{*}$ \\\\", "\\midrule"]
for part, lab in (("device_derived", "device-derived"), ("iid", "IID")):
    for N, pat in ARMS:
        rs = load(pat, part)
        if not rs:
            continue
        b, _, n, _ = bstar(rs)
        sjs = st.median([r["S_JS"] for r in rs])
        marg = st.median([r["mean_vote_margin"] for r in rs])
        acc = st.median([r["clean_ensemble_acc"] for r in rs
                         if r.get("clean_ensemble_acc") is not None])
        rows.append(f"{lab} & {N} & {n} & {sjs:.3f} & {marg:.3f} & {acc:.3f} & {b:.3f} \\\\")
rows += ["\\bottomrule", "\\end{tabular}"]
os.makedirs(OUT, exist_ok=True)
open(f"{OUT}/tab_fedsize.tex", "w").write("\n".join(rows) + "\n")

# macros, so the prose beside the table cannot drift from it (the appendix is
# exempt from the literal gate, and its margins had drifted to a 3-draw value)
mac = ["% GENERATED by scripts/gen_fedsize.py -- do not edit"]
for N, pat in ARMS:
    rs = load(pat, "device_derived")
    if rs:
        mac.append("\\newcommand{\\fsMargDev%s}{%.3f}"
                   % ({10: "Ten", 20: "Twenty", 50: "Fifty"}[N],
                      st.median([r["mean_vote_margin"] for r in rs])))
open(f"{OUT}/fedsize_macros.tex", "w").write("\n".join(mac) + "\n")
print("  -> fedsize_macros.tex")
print("\n".join("  " + r for r in rows if "&" in r and "Partition" not in r))
