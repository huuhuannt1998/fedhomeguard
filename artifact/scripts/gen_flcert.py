#!/usr/bin/env python3
"""Anchor against FLCert's published non-IID result (review E3 / Question 4).

FLCert reports certified accuracy 0.81 on MNIST at degree-of-non-IID 0.5 with
1,000 clients and 100 malicious. Comparing raw accuracies across a 10-class and a
binary task is meaningless, so both are expressed against their own trivial
floor -- the quantity the paper anchors everything else to.
"""
import glob, json, os, statistics as st

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
FLCERT_CA, FLCERT_TAU = 0.81, 0.10        # published: MNIST-0.5, 1000 clients, 100 malicious


def cell(part, k=1, beta=0.10):
    r = []
    for f in glob.glob("results/canonical/e5f_*.jsonl"):
        r += [x for x in (json.loads(l) for l in open(f) if l.startswith("{"))
              if x["partition_type"] == part and x["k"] == k and abs(x["beta"] - beta) < 1e-9]
    return st.median([x["CA"] for x in r]), r[0]["tau_triv"], len({x["partition_seed"] for x in r})


dev, tau, n = cell("device_derived")
iid, _, _ = cell("iid")
mac = [f"\\newcommand{{\\fcCA}}{{{FLCERT_CA:.2f}}}",
       f"\\newcommand{{\\fcTau}}{{{FLCERT_TAU:.2f}}}",
       f"\\newcommand{{\\fcRatio}}{{{FLCERT_CA/FLCERT_TAU:.1f}}}",
       f"\\newcommand{{\\fcOursIid}}{{{iid/tau:.2f}}}",
       f"\\newcommand{{\\fcOursDev}}{{{dev/tau:.2f}}}",
       f"\\newcommand{{\\fcDraws}}{{{n}}}",
       # Review r4 (C-W5): a ratio to the floor is bounded by 1/tau, which is 1.37 on
       # this binary task and 10 on MNIST, so it cannot compare the two. The share of
       # the distance from floor to perfect accuracy, (CA - tau)/(1 - tau), can.
       f"\\newcommand{{\\fcNormPub}}{{{(FLCERT_CA - FLCERT_TAU)/(1 - FLCERT_TAU):.2f}}}",
       f"\\newcommand{{\\fcNormIid}}{{{(iid - tau)/(1 - tau):.2f}}}",
       f"\\newcommand{{\\fcNormDev}}{{{(dev - tau)/(1 - tau):.2f}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/flcert_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_flcert.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  at beta=0.10, as a multiple of each task's trivial floor:")
print(f"    FLCert published (MNIST-0.5, 1000 clients)  {FLCERT_CA/FLCERT_TAU:.1f}x")
print(f"    ours, IID control                           {iid/tau:.2f}x")
print(f"    ours, device-derived                        {dev/tau:.2f}x  (below trivial)")
