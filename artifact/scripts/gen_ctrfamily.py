#!/usr/bin/env python3
"""CTR_mal per attack family (review technical comment 5).

CTR_mal -- the fraction of malicious flows both certified and correctly flagged --
is the paper's headline security number, and it is reported in aggregate. IoT-23
labels each malicious flow with its family, and the review's point is that a
certificate covering DDoS but not C&C beacons is a different security statement.
It is: under device-derived skew the aggregate is an average over families whose
coverage differs by more than the aggregate itself moves.

Families below MIN_N test flows are reported but never used in a claim.
"""
import glob, json, os, statistics as st
from collections import defaultdict

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
MIN_N = 100          # fixed before looking: C&C-Torii has 3 flows and cannot support a rate

rows = []
for f in glob.glob("results/canonical/e17_ctrfamily_*.jsonl"):
    rows += [json.loads(l) for l in open(f) if l.startswith("{")]
if not rows:
    raise SystemExit("gen_ctrfamily: no e17 results")

g = defaultdict(lambda: defaultdict(list)); nfam = {}
for r in rows:
    for k, v in (r.get("CTR_mal_by_family") or {}).items():
        g[(r["partition_type"], round(r["beta"], 2))][k].append(v)
    for k, v in (r.get("n_mal_by_family") or {}).items():
        nfam[k] = v
usable = sorted([f for f in nfam if nfam[f] >= MIN_N], key=lambda f: -nfam[f])
dropped = sorted(set(nfam) - set(usable))


def med(part, beta, fam):
    v = g.get((part, beta), {}).get(fam)
    return st.median(v) if v else None


def agg(part, beta):
    v = [r["CTR_mal"] for r in rows
         if r["partition_type"] == part and abs(r["beta"] - beta) < 1e-9]
    return st.median(v) if v else None


# the spread the aggregate hides, at the last budget where anything certifies
dev10 = {f: med("device_derived", 0.10, f) for f in usable}
dev10 = {f: v for f, v in dev10.items() if v is not None}
iid_vals = [med("iid", 0.40, f) for f in usable]
iid_vals = [v for v in iid_vals if v is not None]

mac = [f"\\newcommand{{\\ctrFamMinN}}{{{MIN_N}}}",
       f"\\newcommand{{\\ctrFamUsable}}{{{len(usable)}}}",
       f"\\newcommand{{\\ctrFamDropped}}{{{len(dropped)}}}",
       f"\\newcommand{{\\ctrDevAggZero}}{{{agg('device_derived',0.0):.4f}}}",
       f"\\newcommand{{\\ctrDevAttackZero}}{{{med('device_derived',0.0,'Attack'):.4f}}}",
       f"\\newcommand{{\\ctrDevAggTen}}{{{agg('device_derived',0.10):.4f}}}",
       f"\\newcommand{{\\ctrDevCCTen}}{{{med('device_derived',0.10,'C&C'):.4f}}}",
       f"\\newcommand{{\\ctrDevDDoSTen}}{{{med('device_derived',0.10,'DDoS'):.4f}}}",
       f"\\newcommand{{\\ctrDevScanTen}}{{{med('device_derived',0.10,'PartOfAHorizontalPortScan'):.4f}}}",
       f"\\newcommand{{\\ctrDevSpreadTen}}{{{max(dev10.values())-min(dev10.values()):.4f}}}",
       f"\\newcommand{{\\ctrIidMinForty}}{{{min(iid_vals):.4f}}}",
       f"\\newcommand{{\\ctrAttackN}}{{{nfam.get('Attack',0)}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/ctrfamily_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_ctrfamily.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  families: {len(usable)} usable (n>={MIN_N}), {len(dropped)} dropped {dropped}")
print(f"  device beta=0.00: aggregate {agg('device_derived',0.0):.4f}, "
      f"Attack {med('device_derived',0.0,'Attack'):.4f} (n={nfam.get('Attack')})")
print(f"  device beta=0.10: aggregate {agg('device_derived',0.10):.4f}, "
      f"C&C {med('device_derived',0.10,'C&C'):.4f}, DDoS {med('device_derived',0.10,'DDoS'):.4f}, "
      f"spread {max(dev10.values())-min(dev10.values()):.4f}")
print(f"  IID worst family at beta=0.40: {min(iid_vals):.4f}")
