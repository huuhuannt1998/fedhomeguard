#!/usr/bin/env python3
"""Score the predeclared k=2 richness test (predeclarations/richness_k2.md).

Thresholds fixed before the runs:
  P1  at 1-3 device types, beta*/beta_geo is HIGHER at k=2 than k=1
  P2  at 2-5 types and above, both k reach >= 0.8 of their own ceiling
  P3  raw beta* at k=2 never exceeds beta_geo(20,2) = 0.250   [bug check]

beta_geo(20,k) is the exact finite-N ceiling, so the two k are only comparable
after normalising by it -- raising k buys agreement and spends headroom.
"""
import glob, json, os, statistics as st, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bstar import bstar

OUT = "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated"
GEO = {1: 0.450, 2: 0.250}
LEV = [("1", "e11b_dph1_1", "e22_k2rich_1_1"),
       ("1--3", "e11b_dph1_3", "e22_k2rich_1_3"),
       ("2--5", "e11b_dph2_5", "e22_k2rich_2_5"),
       ("3--8", "e11b_dph3_8", "e22_k2rich_3_8"),
       ("5--10", "e11b_dph5_10", "e22_k2rich_5_10")]


def arm(stem, k):
    f = f"results/canonical/{stem}.jsonl"
    if not os.path.exists(f):
        return None
    rs = [x for x in (json.loads(l) for l in open(f) if l.startswith("{"))
          if x["partition_type"] == "device_derived" and x["k"] == k]
    if not rs:
        return None
    b, _, n, _ = bstar(rs)
    return dict(bstar=b, norm=b / GEO[k], n=n)


print(f"  {'devices':<9}{'k=1 beta*':>11}{'/ceiling':>10}{'k=2 beta*':>11}{'/ceiling':>10}")
rows = {}
for lab, s1, s2 in LEV:
    a1, a2 = arm(s1, 1), arm(s2, 2)
    if a1 is None or a2 is None:
        print(f"  {lab:<9}{'  (k=2 not run)':>42}"); continue
    rows[lab] = (a1, a2)
    print(f"  {lab:<9}{a1['bstar']:>11.3f}{a1['norm']:>10.2f}{a2['bstar']:>11.3f}{a2['norm']:>10.2f}")
if len(rows) < len(LEV):
    raise SystemExit("\n  incomplete; rerun when the sweep finishes")

p1 = rows["1--3"][1]["norm"] > rows["1--3"][0]["norm"] + 1e-9
p2 = all(min(a1["norm"], a2["norm"]) >= 0.8
         for lab, (a1, a2) in rows.items() if lab in ("2--5", "3--8", "5--10"))
p3 = all(a2["bstar"] <= GEO[2] + 1e-9 for _, a2 in rows.values())
print(f"\n  PREDECLARED SCORING")
print(f"    P1  k=2 normalised beta* higher at 1--3 types  "
      f"({rows['1--3'][0]['norm']:.2f} -> {rows['1--3'][1]['norm']:.2f})   {'PASS' if p1 else 'FAIL'}")
print(f"    P2  both k >= 0.8 of ceiling from 2--5 upward                  {'PASS' if p2 else 'FAIL'}")
print(f"    P3  k=2 raw beta* never exceeds {GEO[2]}  [bug check]          {'PASS' if p3 else 'FAIL'}")

mac = [f"\\newcommand{{\\ktwoNormPoor}}{{{rows['1--3'][1]['norm']:.2f}}}",
       f"\\newcommand{{\\koneNormPoor}}{{{rows['1--3'][0]['norm']:.2f}}}",
       f"\\newcommand{{\\ktwoBstarPoor}}{{{rows['1--3'][1]['bstar']:.3f}}}",
       f"\\newcommand{{\\ktwoBstarRich}}{{{rows['5--10'][1]['bstar']:.3f}}}",
       f"\\newcommand{{\\ktwoDraws}}{{{rows['1--3'][1]['n']}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/k2rich_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_richness_k2.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  -> {OUT}/k2rich_macros.tex")
