#!/usr/bin/env python3
"""Macros for the vote-shaping attack (review W8/E6).

The paper observed that every evaluated attack competes on parameter
displacement and saturates at ALIE, inferred that the binding axis is ensemble
agreement, and said it had not built an attack on that axis. This builds one and
measures it against a BUDGET-MATCHED control, because the interesting question is
whether targeting buys anything, not whether corrupting labels does.
"""
import glob, json, os, statistics as st
from collections import defaultdict

OUT = "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated"
rows = []
for f in glob.glob("results/canonical/e15_voteshape_*.jsonl"):
    rows += [json.loads(l) for l in open(f) if l.startswith("{")]
if not rows:
    raise SystemExit("gen_voteshape: no e15 results")

ea = defaultdict(lambda: defaultdict(list))
cert = defaultdict(list)
for r in rows:
    key = (r["partition_type"], r["k"], round(r["beta"], 3))
    for a, v in (r.get("EA_final_round") or {}).items():
        ea[key][a].append(v)
    cw, cv = r.get("frac_certified_wrong"), r.get("coverage")
    if cw is not None and cv:
        cert[key].append(cw / cv)

win = tie = loss = 0
for key, d in ea.items():
    if "vote_shape" not in d or "rand_flip" not in d:
        continue
    vs, rf = st.median(d["vote_shape"]), st.median(d["rand_flip"])
    if vs < rf - 1e-6: win += 1
    elif vs > rf + 1e-6: loss += 1
    else: tie += 1

def cerr(p, k, b):
    v = cert.get((p, k, round(b, 3)))
    return st.median(v) if v else None

# the load-bearing claim: no (partition, k) has an err|certified above its beta=0 value
exceed = 0
for (p, k) in {(p, k) for (p, k, _) in cert}:
    seq = [(b, st.median(v)) for (pp, kk, b), v in cert.items() if (pp, kk) == (p, k)]
    base = dict(seq).get(0.0)
    if base is None:
        continue
    if max(v for _, v in seq) > base + 1e-4:
        exceed += 1

mac = [f"\\newcommand{{\\vsCells}}{{{win + tie + loss}}}",
       f"\\newcommand{{\\vsWins}}{{{win}}}",
       f"\\newcommand{{\\vsTies}}{{{tie}}}",
       f"\\newcommand{{\\vsLosses}}{{{loss}}}",
       f"\\newcommand{{\\vsExceed}}{{{exceed}}}",
       f"\\newcommand{{\\vsCertErrIIDzero}}{{{cerr('iid',1,0.0):.4f}}}",
       f"\\newcommand{{\\vsCertErrIIDhi}}{{{cerr('iid',1,0.40):.4f}}}",
       f"\\newcommand{{\\vsCertErrDevZero}}{{{cerr('device_derived',1,0.0):.4f}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/voteshape_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_voteshape.py -- do not edit\n")
    fh.write("\n".join(mac) + "\n")
print(f"  matched-budget cells: {win+tie+loss}  (vote_shape wins {win}, ties {tie}, loses {loss})")
print(f"  (partition,k) groups whose err|certified exceeds its beta=0 value: {exceed}")
print(f"  -> {OUT}/voteshape_macros.tex")
