#!/usr/bin/env python3
"""Macros for the adaptive-attack arm.

Objection: EA_ens minimises over five PUBLISHED attacks, none designed against a
plurality-vote ensemble, so the reported slack could be an artifact of a weak suite.
This arm adds an adaptive white-box attack that solves for the FedAvg aggregate and
measures whether it lowers EA anywhere. It does not -- which is the point.
"""
import glob, json, os, re, statistics as st, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from aggregate import src   # review r6: alie/gaussian corrected where the NaN path fired

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
PUB = ["label_flip", "sign_flip", "gaussian", "ipm", "alie"]

rows = []
for f in glob.glob(src("adaptive_iid.jsonl")) + \
         glob.glob(src("adaptive_device_derived.jsonl")):
    for l in open(f):
        if l.startswith("{"):
            rows.append(json.loads(l))

cells = [r for r in rows if r.get("EA_final_round")]
# wins and the cell count must share one filter: reporting wins over the device
# subset beside a cell count over both partitions is the same defect as NdrawsFine.
wins = sum(1 for r in cells
           if r["EA_final_round"].get("adaptive", 1) <
              min(r["EA_final_round"][a] for a in PUB if a in r["EA_final_round"]) - 1e-9)
# worst deficit: how far ABOVE the published minimum the adaptive attack sits
defs_ = [r["EA_final_round"]["adaptive"] -
         min(r["EA_final_round"][a] for a in PUB if a in r["EA_final_round"])
         for r in cells if "adaptive" in r["EA_final_round"]]

# Review r6: with alie/gaussian corrected, the adaptive attack beats the published
# minimum on some k=2 cells. The prose says "all at k=2" and quotes the largest margin,
# so both are computed here and the script refuses if the first stops being true.
pubmin = lambda r: min(r["EA_final_round"][a] for a in PUB if a in r["EA_final_round"])
win_rows = [r for r in cells if r["EA_final_round"].get("adaptive", 1) < pubmin(r) - 1e-9]
if any(r["k"] != 2 for r in win_rows):
    raise SystemExit("adaptive wins outside k=2 -- the appendix sentence must change")
max_win = max((pubmin(r) - r["EA_final_round"]["adaptive"] for r in win_rows), default=0.0)

sc = {}
for f in glob.glob(src("adaptive_scale_*.jsonl")):
    s_ = re.search(r"adaptive_scale_([\d.]+)\.jsonl", f).group(1)
    rr = [json.loads(l) for l in open(f) if l.startswith("{")]
    if rr:
        sc[float(s_)] = (st.median([x["EA_final_round"]["adaptive"] for x in rr]),
                         st.median([x["EA_final_round"]["alie"] for x in rr]))

m = {
    "adCells": str(len(cells)),
    "adWins": str(wins),
    "adWorstDeficit": f"{max(defs_):.4f}" if defs_ else "--",
    "adMedDeficit": f"{st.median(defs_):.4f}" if defs_ else "--",
    "adScaleLo": f"{min(sc):g}" if sc else "--",
    "adScaleHi": f"{max(sc):g}" if sc else "--",
    "adScaleBest": f"{min(sc.values(), key=lambda t: t[0])[0]:.4f}" if sc else "--",
    "adAlieRef": f"{st.median([v[1] for v in sc.values()]):.4f}" if sc else "--",
    "adNScales": str(len(sc)),
    "adMaxWin": f"{max_win:.4f}",
}
os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "adaptive_macros.tex"), "w") as f:
    f.write("% GENERATED by scripts/gen_adaptive.py -- do not edit.\n")
    for k, v in sorted(m.items()):
        f.write("\\newcommand{\\%s}{%s}\n" % (k, v))
print("wrote adaptive_macros.tex")
for k, v in sorted(m.items()):
    print(f"  {k:16s} {v}")
