#!/usr/bin/env python3
"""Tables added for the JISA version (rounds jisa2 and jisa3, 2026-10-16). Writes generated/tab_assumptions.tex from
scripts/jisa_assumptions.yaml, generated/tab_certfl.tex from scripts/jisa_certfl.yaml and generated/tab_variants.tex from
scripts/jisa_variants.yaml (round jisa4). No number is computed here: the rows are qualitative, and every number in them must
appear in an accepted evidence use (the manuscript gate's `numbers` check reads the built table)."""
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _manuscript import GENERATED as OUT  # noqa: E402  (FHG_GENERATED overrides)

HERE = os.path.dirname(os.path.abspath(__file__))
rows = yaml.safe_load(open(os.path.join(HERE, "jisa_assumptions.yaml")))["rows"]
out = ["% GENERATED by scripts/gen_jisa_tables.py from scripts/jisa_assumptions.yaml -- do not edit",
       "\\begin{tabular}{>{\\raggedright\\arraybackslash}p{3.9cm}>{\\raggedright\\arraybackslash}p{3.9cm}"
       ">{\\raggedright\\arraybackslash}p{3.9cm}>{\\raggedright\\arraybackslash}p{1.9cm}}",
       "\\toprule",
       "Assumption & What the experiments show & What they do not license & Where \\\\",
       "\\midrule"]
for i, r in enumerate(rows):
    if i:
        out.append("\\addlinespace[3pt]")
    out.append(" & ".join(str(r[k]) for k in ("assumption", "shows", "not_licensed", "where")) + " \\\\")
out += ["\\bottomrule", "\\end{tabular}"]
os.makedirs(OUT, exist_ok=True)
open(os.path.join(OUT, "tab_assumptions.tex"), "w").write("\n".join(out) + "\n")
print(f"wrote {os.path.join(OUT, 'tab_assumptions.tex')} ({len(rows)} rows)")

# round jisa3 (feedback F9): certified poisoning defenses side by side, values as reported in each paper
crows = yaml.safe_load(open(os.path.join(HERE, "jisa_certfl.yaml")))["rows"]
P = ">{\\raggedright\\arraybackslash}p"
out = ["% GENERATED by scripts/gen_jisa_tables.py from scripts/jisa_certfl.yaml -- do not edit",
       "\\begin{tabular}{" + P + "{2.9cm}" + P + "{3.0cm}" + P + "{3.1cm}" + P + "{3.2cm}" + P + "{5.4cm}}",
       "\\toprule",
       "Defense & Budget counts & Certificate & Setting; data & Operating point reported \\\\",
       "\\midrule"]
for i, r in enumerate(crows):
    if i == len(crows) - 1:
        out.append("\\midrule")
    elif i:
        out.append("\\addlinespace[2pt]")
    out.append(" & ".join(str(r[k]) for k in ("defense", "budget", "certificate", "setting", "point")) + " \\\\")
out += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tab_certfl.tex"), "w").write("\n".join(out) + "\n")
print(f"wrote {os.path.join(OUT, 'tab_certfl.tex')} ({len(crows)} rows)")

# round jisa4 (AutoResearchClaw r1 C9, editor (a)6): values of the same quantity, their statistic and draws
vrows = yaml.safe_load(open(os.path.join(HERE, "jisa_variants.yaml")))["rows"]
out = ["% GENERATED by scripts/gen_jisa_tables.py from scripts/jisa_variants.yaml -- do not edit",
       "\\begin{tabular}{" + P + "{3.6cm}" + P + "{1.9cm}" + P + "{1.8cm}" + P + "{3.8cm}" + P + "{3.0cm}}",
       "\\toprule",
       "Quantity & Value & Statistic & Draws & Where \\\\",
       "\\midrule"]
for i, r in enumerate(vrows):
    if i and r["quantity"] != vrows[i - 1]["quantity"]:
        out.append("\\addlinespace[3pt]")
    out.append(" & ".join(str(r[k]) for k in ("quantity", "value", "statistic", "draws", "where")) + " \\\\")
out += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tab_variants.tex"), "w").write("\n".join(out) + "\n")
print(f"wrote {os.path.join(OUT, 'tab_variants.tex')} ({len(vrows)} rows)")
