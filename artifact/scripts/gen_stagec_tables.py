#!/usr/bin/env python3
"""Stage-C tables for the TMLR manuscript (Writer outline O-001; numbers bound to P-003@2, P-005,
P-010, P-014, P-015).

  tab_main.tex        certified accuracy and certified detection by k and beta, IID and
                      device-derived. Round tmlr4 (2026-10-10): k <= 2 from the 30-draw certified grid
                      (results/canonical/e5f_*.jsonl, seeds 10-39), the source of Table tab:ids and of the
                      prior analysis, with the interquartile range of device-derived certified accuracy;
                      k = 3 stays the sampled same-ensemble arm (K = 500, 3 draws x 3 malicious sets), the
                      numbers.tex macros (\\CAIID, \\CADEV, \\CTRIID, \\CTRDEV) of
                      scripts/gen_paper_numbers.py. No number is retyped.
  tab_slackdecomp.tex predictor loss vs added slack per informative device-derived cell: cells
                      are the \\DECOMPCOMP / \\DECOMPSLACK macros of the same generator.
  tab_ceiling.tex     exact ceiling beta_geo(N,k) for N in {20, 50, 1000} from results/beta_geo.json,
                      and the large-N ceiling 1 - 2^(-1/k).

Writes into $FHG_GENERATED (the manuscript's generated/ folder).
"""
import json, os

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
KS, BETAS = (1, 2, 3), ("0", "5", "10", "20", "30", "40")
BLAB = {"0": "0.00", "5": "0.05", "10": "0.10", "20": "0.20", "30": "0.30", "40": "0.40"}

# --- tab_main (round tmlr4: k <= 2 from the 30-draw grid; k = 3 from the sampled arm's macros)
import numpy as np  # noqa: E402

here = os.path.dirname(os.path.abspath(__file__))


def _e5f_cells():
    """{(kind, k, beta label): (median CA, q25 CA, q75 CA, median CTR_mal, void)} over the 30 draws."""
    cells = {}
    for kind, tag in (("iid", "IID"), ("device_derived", "DEV")):
        rows = [json.loads(l) for l in open(os.path.join(here, "..", "results", "canonical", f"e5f_{kind}.jsonl"))
                if l.strip()]
        for k in (1, 2):
            for b in BETAS:
                v = [r for r in rows if r["k"] == k and abs(r["beta"] - int(b) / 100) < 1e-9]
                assert len(v) == 30, (kind, k, b, len(v))
                ca = np.array([r["CA"] for r in v], float)
                cells[(tag, k, b)] = (float(np.median(ca)), float(np.percentile(ca, 25)), float(np.percentile(ca, 75)),
                                      float(np.median([r["CTR_mal"] for r in v])),
                                      not any(r["combinatorially_possible"] for r in v))
    return cells


E5F = _e5f_cells()


def _cell(tag, k, b, iqr):
    med, q25, q75, ctr, void = E5F[(tag, k, b)]
    ca = f"{med:.4f}" + (f" [{q25:.2f}, {q75:.2f}]" if iqr and not void else "")
    return ca, f"{ctr:.4f}"


o = ["% GENERATED by scripts/gen_stagec_tables.py -- do not edit", "\\begin{tabular}{llcccc}", "\\toprule",
     "& & \\multicolumn{2}{c}{certified accuracy} & \\multicolumn{2}{c}{certified detection} \\\\",
     "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
     "$k$ & $\\beta$ & IID & device-derived [IQR] & IID & device-derived \\\\", "\\midrule"]
for i, k in enumerate(KS):
    if i:
        o.append("\\midrule")
    for b in BETAS:
        if k <= 2:
            ca_i, ctr_i = _cell("IID", k, b, False)
            ca_d, ctr_d = _cell("DEV", k, b, True)
            o.append(f"{k} & {BLAB[b]} & {ca_i} & {ca_d} & {ctr_i} & {ctr_d} \\\\")
        else:
            o.append(f"{k}$^{{\\dagger}}$ & {BLAB[b]} & \\CAIID{{{k}}}{{{b}}} & \\CADEV{{{k}}}{{{b}}} & "
                     f"\\CTRIID{{{k}}}{{{b}}} & \\CTRDEV{{{k}}}{{{b}}} \\\\")
o += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tab_main.tex"), "w").write("\n".join(o) + "\n")

# --- tab_slackdecomp: the 7 informative device-derived cells (non-void, beta > 0, attacked
# accuracy above tau_triv), as listed in P-015.
INFO = [(1, "5"), (1, "10"), (2, "5"), (2, "10"), (2, "20"), (3, "5"), (3, "10")]
o = ["% GENERATED by scripts/gen_stagec_tables.py -- do not edit", "\\begin{tabular}{llcc}", "\\toprule",
     "$k$ & $\\beta$ & predictor loss & added slack \\\\", "\\midrule"]
for k, b in INFO:
    o.append(f"{k} & {BLAB[b]} & \\DECOMPCOMP{{{k}}}{{{b}}} & \\DECOMPSLACK{{{k}}}{{{b}}} \\\\")
o += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tab_slackdecomp.tex"), "w").write("\n".join(o) + "\n")

# --- tab_ceiling
bg = json.load(open(os.path.join(here, "..", "results", "beta_geo.json")))["beta_geo"]
o = ["% GENERATED by scripts/gen_stagec_tables.py from results/beta_geo.json -- do not edit",
     "\\begin{tabular}{lcccc}", "\\toprule",
     "$k$ & $N=20$ & $N=50$ & $N=1000$ & large $N$, $1-2^{-1/k}$ \\\\", "\\midrule"]
for k in (1, 2, 3, 5, 8):
    cells = " & ".join("%.3f" % bg[f"N{n}_k{k}"] for n in (20, 50, 1000))
    o.append(f"{k} & {cells} & {1 - 2 ** (-1 / k):.3f} \\\\")
o += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(OUT, "tab_ceiling.tex"), "w").write("\n".join(o) + "\n")
print("wrote tab_main.tex, tab_slackdecomp.tex, tab_ceiling.tex")
