#!/usr/bin/env python3
"""A stronger local learner at k=1 (review W3 / E2).

The paper's second family is WEAKER than the perceptron (logistic regression, 64
parameters). The review asks the other direction: does a stronger learner rescue
competence? A 128-64-32 MLP is roughly 24x the perceptron's parameter count.

It does not, and the way it fails is the paper's thesis: the larger model buys
ensemble ACCURACY and not vote MARGIN, and certification consumes the margin.

Matched on the three partition draws both arms share -- the mlp_large arm has
three, so comparing it to the thirty-draw e5f arm would not be a comparison.
The IID beta* is deliberately not reported: the baseline arm's grid stops at
0.40 and is right-censored there, so the two are not measuring the same thing.
"""
import glob, json, os, statistics as st, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bstar import bstar
from aggregate import src as _src   # review r6: corrected same-predictor rows

OUT = os.environ.get("FHG_GENERATED",
                     "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated")


def load(pat, part, k=1):
    r = []
    for f in glob.glob(pat):
        r += [x for x in (json.loads(l) for l in open(f) if l.startswith("{"))
              if x["partition_type"] == part and x["k"] == k]
    return r


big = load("results/canonical/e19_large_device_derived.jsonl", "device_derived")
base = load(_src("e2_device_derived_*.jsonl"), "device_derived")
seeds = sorted({r["partition_seed"] for r in big} & {r["partition_seed"] for r in base})
big = [r for r in big if r["partition_seed"] in seeds]
base = [r for r in base if r["partition_seed"] in seeds]
bb, _, _, _ = bstar(big); bs, _, _, _ = bstar(base)
mac = [f"\\newcommand{{\\bigMargin}}{{{st.median([r['mean_vote_margin'] for r in big]):.4f}}}",
       f"\\newcommand{{\\bigMarginBase}}{{{st.median([r['mean_vote_margin'] for r in base]):.4f}}}",
       f"\\newcommand{{\\bigAcc}}{{{st.median([r['clean_ensemble_acc'] for r in big if r.get('clean_ensemble_acc') is not None]):.4f}}}",
       f"\\newcommand{{\\bigAccBase}}{{{st.median([r['clean_ensemble_acc'] for r in base if r.get('clean_ensemble_acc') is not None]):.4f}}}",
       f"\\newcommand{{\\bigDraws}}{{{len(seeds)}}}",
       f"\\newcommand{{\\bigSameBstar}}{{{'yes' if abs(bb-bs) < 1e-9 else 'no'}}}"]
# Review r6 item 13: parameter counts computed from the models, not typed. The appendix
# had "24x" for the 128-64-32 network; on 31 features with 2 outputs it is 9.1x.
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
from fedhomeguard import config as _CFG, data as _DATA
from fedhomeguard.models import build_model as _bm, n_params as _np
_cfg = _CFG.load("configs/stage3_certification.yaml"); _cfg.device = "cpu"
_d = _DATA.load_dataset(_cfg, verbose=False)["X"].shape[1]
def _params(arch):
    _cfg.model.arch = arch
    return _np(_bm(_cfg, _d))
_pm, _pl, _pb = _params("mlp"), _params("logreg"), _params("mlp_large")
_grp = lambda v: f"{v:,}".replace(",", "{,}")
mac += [f"\\newcommand{{\\paramsMLP}}{{{_grp(_pm)}}}",
        f"\\newcommand{{\\paramsLR}}{{{_grp(_pl)}}}",
        f"\\newcommand{{\\paramsBig}}{{{_grp(_pb)}}}",
        f"\\newcommand{{\\paramsBigRatio}}{{{_pb / _pm:.1f}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/bigmodel_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_bigmodel.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  matched on {len(seeds)} draws (device-derived, k=1):")
print(f"    margin  {st.median([r['mean_vote_margin'] for r in base]):.4f} -> "
      f"{st.median([r['mean_vote_margin'] for r in big]):.4f}")
print(f"    acc     {st.median([r['clean_ensemble_acc'] for r in base if r.get('clean_ensemble_acc') is not None]):.4f} -> "
      f"{st.median([r['clean_ensemble_acc'] for r in big if r.get('clean_ensemble_acc') is not None]):.4f}")
print(f"    beta*   {bs:.3f} -> {bb:.3f}  ({'unchanged' if abs(bb-bs)<1e-9 else 'changed'})")
