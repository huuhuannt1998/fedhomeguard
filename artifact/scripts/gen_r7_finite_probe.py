#!/usr/bin/env python3
"""Macros for the r7 finiteness probe (scripts/probe_r7_finite.py).

Reads results/r7_finite_probe/probe.jsonl and writes generated/fp_macros.tex:
  \\fpDraws            collapsed draws probed (Section 6.3's finite-attack collapses)
  \\fpMembers          touched members probed across them
  \\fpNonFiniteDraws   draws whose winning attack left ANY member non-finite
  \\fpNonFiniteMembers members with a non-finite update, aggregate or final weights
  \\fpEAMatch          draws whose rebuilt attacked accuracy equals the recorded one
Refuses to write if a draw's rebuilt accuracy does not reproduce the recorded value.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IN = os.path.join(ROOT, "results", "r7_finite_probe", "probe.jsonl")
from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)


def main():
    rs = [json.loads(l) for l in open(IN) if l.strip()]
    mac = dict(
        fpDraws=len(rs),
        fpMembers=sum(r["touched"] for r in rs),
        fpNonFiniteDraws=sum(r["members_nonfinite_any"] > 0 for r in rs),
        fpNonFiniteMembers=sum(r["members_nonfinite_any"] for r in rs),
        fpEAMatch=sum(r["EA_match"] for r in rs),
    )
    print(mac)
    by = {}
    for r in rs:
        b = by.setdefault((r["partition"], r["k"], r["attack"]), [0, 0, 0])
        b[0] += 1; b[1] += r["members_nonfinite_any"] > 0; b[2] += r["touched"]
    for kk, v in sorted(by.items()):
        print(f"  {kk}: draws {v[0]}, with non-finite members {v[1]}, members {v[2]}")
    if mac["fpEAMatch"] != mac["fpDraws"]:
        print("rebuilt accuracy does not reproduce every draw -- refusing"); return 1
    with open(os.path.join(OUT, "fp_macros.tex"), "w") as fh:
        fh.write("% GENERATED by scripts/gen_r7_finite_probe.py -- do not edit\n")
        for k, v in mac.items():   # thousands separator in the paper's register
            fh.write("\\newcommand{\\%s}{%s}\n" % (k, f"{v:,}".replace(",", "{,}")))
    print(f"wrote {OUT}/fp_macros.tex")
    return 0


if __name__ == "__main__":
    sys.exit(main())
