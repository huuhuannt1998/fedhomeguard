#!/usr/bin/env python3
"""Leave-one-device-out macros (review W7/E5).

The default protocol splits time-ordered within each device, so every test device
is a training device: it measures generalisation across time, not across devices,
which is what a federated IDS is deployed to do. This holds each IoT-23 capture
out of training entirely and tests only on it.

The answer is mostly about the dataset. A single capture is close to
class-homogeneous, so the trivial floor moves to the fold and is often degenerate;
where it is not, the partition scheme barely matters, because the shift between
devices dominates the shift between partitions.
"""
import json, os, statistics as st
from collections import defaultdict

OUT = "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated"
rows = [json.loads(l) for l in open("results/canonical/e16_lodo.jsonl") if l.startswith("{")]
by = defaultdict(lambda: defaultdict(list))
for r in rows:
    if r["beta"] == 0:
        by[r["tag"]][r["partition_type"]].append(r)

taus, beats, diffs = [], 0, []
for tag, d in by.items():
    tau = d[next(iter(d))][0]["tau_triv"]
    taus.append(tau)
    ca = {p: st.median([x["CA"] for x in v]) for p, v in d.items()}
    if max(ca.values()) > tau:
        beats += 1
    if "iid" in ca and "device_derived" in ca:
        diffs.append(abs(ca["iid"] - ca["device_derived"]))

n = len(taus)
mac = [f"\\newcommand{{\\lodoFolds}}{{{n}}}",
       f"\\newcommand{{\\lodoTauMin}}{{{min(taus):.4f}}}",
       f"\\newcommand{{\\lodoTauMed}}{{{st.median(taus):.4f}}}",
       f"\\newcommand{{\\lodoTauMax}}{{{max(taus):.4f}}}",
       f"\\newcommand{{\\lodoDegenerate}}{{{sum(1 for t in taus if t >= 0.99)}}}",
       f"\\newcommand{{\\lodoUnbeatable}}{{{sum(1 for t in taus if t >= 0.9999)}}}",
       f"\\newcommand{{\\lodoBeats}}{{{beats}}}",
       f"\\newcommand{{\\lodoPartMedDiff}}{{{st.median(diffs):.4f}}}",
       f"\\newcommand{{\\lodoPartMaxDiff}}{{{max(diffs):.4f}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/lodo_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_lodo.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  folds={n}  tau: min={min(taus):.4f} med={st.median(taus):.4f} max={max(taus):.4f}")
print(f"  folds with tau>=0.99: {sum(1 for t in taus if t>=0.99)}   "
      f"tau==1.0000 (nothing can beat trivial): {sum(1 for t in taus if t>=0.9999)}")
print(f"  folds where some partition beats tau: {beats}/{n}")
print(f"  |CA_iid - CA_dev| per fold: median={st.median(diffs):.4f} max={max(diffs):.4f}")
