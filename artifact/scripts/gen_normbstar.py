#!/usr/bin/env python3
"""beta* normalised by the ceiling each k imposes (review technical comment 6).

Comparing raw beta* across k compares quantities with different upper bounds:
beta_geo(20,1)=0.450 but beta_geo(20,2)=0.250, so "triples from k=1 to k=2" is
measured against a ceiling that has itself nearly halved. Normalising by that
ceiling makes the two comparable, and the paired comparison on the comparable
quantity is cleaner than on the raw one.
"""
import glob, json, os, sys, statistics as st
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bstar import bstar_per_draw

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
GEO = {1: 0.450, 2: 0.250}          # beta_geo(20,k), the exact finite-N ceiling

rows = []
for f in glob.glob("results/canonical/e5f_*.jsonl"):
    rows += [json.loads(l) for l in open(f) if l.startswith("{")]
per = {k: bstar_per_draw([r for r in rows if r["k"] == k
                          and r["partition_type"] == "device_derived"]) for k in GEO}
seeds = sorted(set(per[1]) & set(per[2]))
n1 = [per[1][s] / GEO[1] for s in seeds]
n2 = [per[2][s] / GEO[2] for s in seeds]
w = sum(1 for a, b in zip(n1, n2) if b > a)
l = sum(1 for a, b in zip(n1, n2) if b < a)
mac = [f"\\newcommand{{\\BstarNormOne}}{{{st.median(n1):.3f}}}",
       f"\\newcommand{{\\BstarNormTwo}}{{{st.median(n2):.3f}}}",
       f"\\newcommand{{\\BstarNormWin}}{{{w}}}",
       f"\\newcommand{{\\BstarNormTie}}{{{len(seeds)-w-l}}}",
       f"\\newcommand{{\\BstarNormLoss}}{{{l}}}",
       f"\\newcommand{{\\BstarNormN}}{{{len(seeds)}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/normbstar_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_normbstar.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  paired draws {len(seeds)} (seed sets coincide, none discarded)")
print(f"  normalised beta*: k=1 {st.median(n1):.3f} -> k=2 {st.median(n2):.3f} of ceiling")
print(f"  paired: k=2 higher {w}, tie {len(seeds)-w-l}, lower {l}")
