#!/usr/bin/env python3
"""Starvation audit for the skew instrument (review technical comment 4).

S_JS excludes empty clients and the pipeline rejects starved ones, and the review
asked for the threshold and how many draws were rejected per family -- because
rejecting draws biases the surviving sample toward tractable partitions. The
count is not in the result rows (n_starved is logged, not persisted), so the
partitions are rebuilt through the same code path and counted directly.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import contextlib, io
from fedhomeguard import config as CFG, data as DATA, partition as P

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
# Every partition seed an IID or device-derived arm of the paper uses: the main grid
# (0-2), the thirty-draw arm behind Tables 1 and 3 (10-39) and the thirty-draw IID slack
# arm (0-29). The earlier range(30) missed seeds 30-39 of the thirty-draw arm, so the
# printed "0 of 30" did not cover the draws the review read it as covering (r7 item 1).
SEEDS = list(range(40))
FAMILIES = ["iid", "device_derived"]

cfg = CFG.load("configs/stage3_certification.yaml")
bundle = DATA.load_dataset(cfg, verbose=False)
X, y, device = bundle["X"], bundle["y"], bundle["device"]
tr, _ = DATA.time_split_within_device(y, device, cfg.data.train_frac,
                                      block=bundle.get("block"))
ytr, dtr = y[tr], device[tr]
mcr = getattr(cfg.partition, "min_client_rows", 16)

rows = []
for fam in FAMILIES:
    starved_draws = 0
    worst = 0
    for s in SEEDS:
        cfg.partition.kind = fam
        cfg.partition.seed = s
        with contextlib.redirect_stdout(io.StringIO()):
            parts, meta = P.build(cfg, ytr, dtr)
        n = P.count_empty(parts, mcr)
        if n:
            starved_draws += 1
        worst = max(worst, n)
    rows.append((fam, starved_draws, worst))
    print(f"  {fam:<16} draws with a starved client: {starved_draws}/{len(SEEDS)}  "
          f"worst-case starved clients in a draw: {worst}")

mac = [f"\\newcommand{{\\starvMinRows}}{{{mcr}}}",
       f"\\newcommand{{\\starvDraws}}{{{len(SEEDS)}}}"]
for fam, sd, w in rows:
    tag = "Iid" if fam == "iid" else "Dev"
    mac.append(f"\\newcommand{{\\starvRejected{tag}}}{{{sd}}}")
    mac.append(f"\\newcommand{{\\starvWorst{tag}}}{{{w}}}")
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/starvation_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_starvation.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  min_client_rows = {mcr}\n  -> {OUT}/starvation_macros.tex")
