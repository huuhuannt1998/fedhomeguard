#!/usr/bin/env python3
"""ISJ-GP table tab:alternatives (round isj2a plan, O-001@5, Appendix B): the three predeclared alternatives that keep
the members but change how one-class members vote, each prediction as written before the run and the measured result.
Predeclarations (FedHomeGuard-P10/predeclarations/): abstain_feasibility_2026-11-03.md, anomaly_vote_2026-11-03.md,
certified_anomaly_feasibility_2026-11-03.md (with its dated deviation). Verdicts are computed from the rows, not typed.

Reads results/novelty/{abstain_feasibility.json, anomaly_vote_primary.jsonl, certified_anomaly_*.jsonl}. Writes
generated/tab_alternatives.tex and generated/tab_alternatives_numbers.json in the ISJ-GP folder.

    python3 scripts/gen_isj_alternatives_table.py
"""
import hashlib, json, os
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results", "novelty")
OUT = os.environ.get("FHG_OUT") or os.path.join(ROOT, "out")  # artifact: writes out/generated, out/figures
med = lambda a: float(np.median(a))


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def rows_jsonl(name):
    p = os.path.join(RES, name)
    return [json.loads(l) for l in open(p) if l.strip()], sha(p)


def main():
    out, src = [], {}
    # --- abstention (main grid of the member bank, 40 draws)
    p = os.path.join(RES, "abstain_feasibility.json"); src["abstain_feasibility.json"] = sha(p)
    AB = json.load(open(p))["rows"]
    M = [r for r in AB if r["group"] == "main_dd_1-3_k1"]; I = [r for r in AB if r["group"] == "control_iid_k1"]
    gain = med([r["abst_beta_star"] - r["plur_beta_star"] for r in M])
    colP = sum(r["plur_CA20"] <= r["tau"] for r in M); colA = sum(r["abst_CA20"] <= r["tau"] for r in M)
    out += [("Abstention", "P1: median $\\beta^{*}$ gain $\\geq 0.10$", f"{gain:+.2f}", gain >= 0.10 - 1e-9),
            ("", f"P2: collapses at $m=4$ halved (of {len(M)})", f"{colP} $\\to$ {colA}", colA <= colP / 2),
            ("", f"P3: IID control changes on $\\leq 10\\%$ of {len(I)}",
             f"{sum(r['abst_beta_star'] != r['plur_beta_star'] for r in I)} of {len(I)}",
             sum(r['abst_beta_star'] != r['plur_beta_star'] for r in I) <= 0.1 * len(I))]
    # --- one-sided anomaly votes (fresh IoT-23 draws 40-69)
    V, src["anomaly_vote_primary.jsonl"] = rows_jsonl("anomaly_vote_primary.jsonl")
    v1 = med([r["V"]["CTR_mal20"] - r["P"]["CTR_mal20"] for r in V])
    cP = sum(r["P"]["collapse20"] for r in V); cV = sum(r["V"]["collapse20"] for r in V)
    v3 = med([r["V"]["beta_star"] - r["P"]["beta_star"] for r in V])
    v4b = med([r["V"]["CTR_ben20"] - r["P"]["CTR_ben20"] for r in V]); v4f = med([r["V"]["clean_FPR"] - r["P"]["clean_FPR"] for r in V])
    out += [("Anomaly votes", "V1: certified detection gain at $m=4$ $\\geq 0.50$", f"{v1:+.2f}", v1 >= 0.50),
            ("", f"V2: collapses at $m=4$ halved (of {len(V)})", f"{cP} $\\to$ {cV}", cV <= cP / 2),
            ("", "V3: median $\\beta^{*}$ gain $\\geq 0.10$", f"{v3:+.2f}", v3 >= 0.10 - 1e-9),
            ("", "V4: benign certified $\\geq -0.10$, clean FPR $\\leq +0.02$", f"{v4b:+.2f}, {v4f:+.3f}",
             v4b >= -0.10 and v4f <= 0.02)]
    # --- certified anomaly-based ensemble (fresh draws 100-129)
    def ctpr(name, m):
        R, h = rows_jsonl(name); src[name] = h
        sel = [r["by_m"][m]["selected"] for r in R if r.get("status") == "ok"]
        return med([s["cTPR"] if s else 0.0 for s in sel]), sum(s is None for s in sel), len(sel)
    f1, e1, n1 = ctpr("certified_anomaly_nbaiot.jsonl", "2"); f2, e2, n2 = ctpr("certified_anomaly_nbaiot.jsonl", "4")
    f3, e3, n3 = ctpr("certified_anomaly_cic.jsonl", "2"); f4, e4, n4 = ctpr("certified_anomaly_iot23.jsonl", "2")
    out += [("Certified anomaly ensemble", "F1: N-BaIoT, $m=2$, certified detection $\\geq 0.50$", f"{f1:.2f}", f1 >= 0.50),
            ("", "F2: N-BaIoT, $m=4$, certified detection $\\geq 0.30$", f"{f2:.2f} (no threshold on {e2} of {n2})", f2 >= 0.30),
            ("", "F3: CIC IoT-IDAD 2024, $m=2$, $\\geq 0.30$", f"{f3:.2f} (no threshold on {e3} of {n3})", f3 >= 0.30),
            ("", "F4: IoT-23, $m=2$, stays below 0.10", f"{f4:.2f}", f4 < 0.10)]
    lines = ["% GENERATED by scripts/gen_isj_alternatives_table.py -- do not edit",
             "\\begin{tabular}{lllc}", "\\toprule",
             "Alternative & Predeclared prediction & Result & Held \\\\", "\\midrule"]
    for i, (alt, pred, res, held) in enumerate(out):
        if alt and i:
            lines.append("\\midrule")
        lines.append(f"{alt} & {pred} & {res} & {'yes' if held else 'no'} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    os.makedirs(os.path.join(OUT, "generated"), exist_ok=True)
    open(os.path.join(OUT, "generated", "tab_alternatives.tex"), "w").write("\n".join(lines) + "\n")
    json.dump({"sources": src, "rows": [dict(alternative=a, prediction=p, result=r, held=bool(h)) for a, p, r, h in out]},
              open(os.path.join(OUT, "generated", "tab_alternatives_numbers.json"), "w"), indent=1)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
