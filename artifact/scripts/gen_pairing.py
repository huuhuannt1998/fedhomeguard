#!/usr/bin/env python3
"""F11 / review E3: can the richness lever be bought by grouping?

The paper's lever on small-k certification is the device inventory: households
owning more device types train members that see both classes, and beta* rises with
the inventory. CARVY-FL (arXiv 2608.28992) proposes the other lever for the same
failure -- leave the inventory alone and choose the GROUPS so each member spans
several client types. This generator reports the arm that tests it.

THE COMPARISON IS CONTROLLED ON THE GEOMETRY, WHICH IS THE ONLY WAY IT MEANS
ANYTHING. Proposition 1's threshold is 2 c_max(m)/K and c_max reads the realised
subsets alone, so a diversity-chosen ensemble of a different size would move the
vote margins and the threshold together and the result would attribute to grouping
whatever the size did. Both pairing arms are 2-regular with K = N: every household
sits in exactly two pairs, so the degree sequence is fixed and only WHICH households
are paired differs. c_max is still computed exactly on the realised pairs and is
reported here, so a reader can confirm the geometry did not move.

Two context arms come from the existing certified sweep on the same 30 draws:
k=1 (K=20, the paper's cheapest ensemble) and k=2 fully enumerated (K=190).

Reads : results/canonical/e26_pairing_{random,anticluster}.jsonl
        results/canonical/e5f_device_derived.jsonl
Writes: generated/tab_pairing.tex, generated/pairing_macros.tex
"""
import json, math, os, statistics as st, sys

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
CANON = "results/canonical"
BETA_OP = 0.20          # the operating point the body reports for device-derived skew


def load(path):
    return [json.loads(l) for l in open(path) if l.strip()]


def per_draw(rows, seeds):
    """Collapse one arm to one record per partition draw."""
    by = {}
    for r in rows:
        if r["partition_seed"] in seeds:
            by.setdefault(r["partition_seed"], []).append(r)
    out = {}
    for s, rs in by.items():
        # beta*: the largest fraction whose certified accuracy still beats the
        # trivial constant predictor. Same definition as everywhere else in the paper.
        ok = [r["beta"] for r in rs if r["CA"] > r["tau_triv"]]
        op = next((r for r in rs if abs(r["beta"] - BETA_OP) < 1e-9), None)
        zero = next((r for r in rs if r["beta"] == 0.0), None)
        out[s] = dict(
            bstar=max(ok) if ok else 0.0,
            margin=zero["mean_vote_margin"] if zero else None,
            K=zero["K"] if zero else None,
            ca_op=op["CA"] if op else None,
            collapsed_op=bool(op["CA"] <= op["tau_triv"]) if op else None,
            cmax_op=op.get("c_max") if op else None,
            span=(zero.get("pairing_meta") or {}).get("mean_span") if zero else None,
            span_ge2=(zero.get("pairing_meta") or {}).get("frac_span_ge2") if zero else None,
        )
    return out


def med(xs):
    xs = [x for x in xs if x is not None]
    return st.median(xs) if xs else float("nan")


def main():
    arms = {m: load(f"{CANON}/e26_pairing_{m}.jsonl")
            for m in ("random", "anticluster")}
    e5f = load(f"{CANON}/e5f_device_derived.jsonl")

    # Paired design: only draws present in every arm, so every comparison below is
    # between the same households under different groupings.
    seedsets = [{r["partition_seed"] for r in v} for v in arms.values()]
    seedsets.append({r["partition_seed"] for r in e5f})
    seeds = set.intersection(*seedsets)
    if len(seeds) < 30:
        sys.exit(f"FAIL: only {len(seeds)} draws complete in every arm; "
                 "the table claims 30 and must not be emitted short")

    rows = {
        "k=1, all singletons": per_draw([r for r in e5f if r["k"] == 1], seeds),
        "k=2, random pairs": per_draw(arms["random"], seeds),
        "k=2, anticlustered pairs": per_draw(arms["anticluster"], seeds),
        "k=2, all pairs": per_draw([r for r in e5f if r["k"] == 2], seeds),
    }

    # The controlled claim: the two pairing arms must share K and the realised c_max
    # at the operating point, or the comparison is about geometry after all.
    kr = {d["K"] for d in rows["k=2, random pairs"].values()}
    ka = {d["K"] for d in rows["k=2, anticlustered pairs"].values()}
    cr = {d["cmax_op"] for d in rows["k=2, random pairs"].values()}
    ca = {d["cmax_op"] for d in rows["k=2, anticlustered pairs"].values()}
    if kr != ka:
        sys.exit(f"FAIL: pairing arms differ in K ({kr} vs {ka})")
    geom_identical = (cr == ca and len(cr) == 1)

    lines = ["% GENERATED by scripts/gen_pairing.py -- do not edit",
             r"\begin{tabular}{@{}l@{\;\;}c@{\;\;}c@{\;\;}c@{\;\;}c@{\;\;}c@{}}",
             r"\toprule",
             r"Ensemble & $K$ & margin & $\beta^\ast$ & CA$(\beta{=}0.20)$ "
             r"& collapse \\",
             r"\midrule"]
    for name, d in rows.items():
        vals = list(d.values())
        K = int(med([v["K"] for v in vals]))
        ncol = sum(1 for v in vals if v["collapsed_op"])
        lines.append(
            f"{name} & {K} & {med([v['margin'] for v in vals]):.4f} & "
            f"{med([v['bstar'] for v in vals]):.3f} & "
            f"{med([v['ca_op'] for v in vals]):.4f} & {ncol}/{len(vals)} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(OUT, exist_ok=True)
    open(f"{OUT}/tab_pairing.tex", "w").write("\n".join(lines) + "\n")

    R = rows["k=2, random pairs"]
    A = rows["k=2, anticlustered pairs"]
    dm = [A[s]["margin"] - R[s]["margin"] for s in seeds]
    db = [A[s]["bstar"] - R[s]["bstar"] for s in seeds]
    n_up = sum(1 for x in db if x > 0)
    n_dn = sum(1 for x in db if x < 0)
    # The four-arm table is emitted (generated/tab_pairing.tex, float ready to drop in)
    # but the paper is at 18/18 pages and could not seat another float, so the prose
    # carries the comparison. These macros are what it needs to do that without the
    # table: every arm's beta* and margin, so no number lives only in the float.
    def arm(nm, field):
        return med([v[field] for v in rows[nm].values()])
    mac = [
        f"\\newcommand{{\\PairBstarSingles}}{{{arm('k=1, all singletons','bstar'):.3f}}}",
        f"\\newcommand{{\\PairBstarRand}}{{{arm('k=2, random pairs','bstar'):.3f}}}",
        f"\\newcommand{{\\PairBstarAnti}}{{{arm('k=2, anticlustered pairs','bstar'):.3f}}}",
        f"\\newcommand{{\\PairBstarAllPairs}}{{{arm('k=2, all pairs','bstar'):.3f}}}",
        f"\\newcommand{{\\PairMargRand}}{{{arm('k=2, random pairs','margin'):.4f}}}",
        f"\\newcommand{{\\PairMargAnti}}{{{arm('k=2, anticlustered pairs','margin'):.4f}}}",
        f"\\newcommand{{\\PairDraws}}{{{len(seeds)}}}",
        f"\\newcommand{{\\PairK}}{{{sorted(kr)[0]}}}",
        f"\\newcommand{{\\PairSpanRand}}{{{med([v['span'] for v in R.values()]):.2f}}}",
        f"\\newcommand{{\\PairSpanAnti}}{{{med([v['span'] for v in A.values()]):.2f}}}",
        f"\\newcommand{{\\PairMarginGain}}{{{st.mean(dm):+.4f}}}",
        f"\\newcommand{{\\PairBstarGain}}{{{st.mean(db):+.4f}}}",
        f"\\newcommand{{\\PairBstarUp}}{{{n_up}}}",
        f"\\newcommand{{\\PairBstarDown}}{{{n_dn}}}",
        f"\\newcommand{{\\PairBstarSame}}{{{len(seeds) - n_up - n_dn}}}",
        # the inventory lever, for the sentence that contrasts the two
        f"\\newcommand{{\\PairGeomIdentical}}{{{'yes' if geom_identical else 'no'}}}",
    ]
    open(f"{OUT}/pairing_macros.tex", "w").write(
        "% GENERATED by scripts/gen_pairing.py -- do not edit\n" + "\n".join(mac) + "\n")

    print(f"wrote tab_pairing.tex, pairing_macros.tex ({len(mac)} macros)")
    print(f"  {len(seeds)} paired draws, K={sorted(kr)[0]}, "
          f"realised c_max at beta=0.20 identical across arms: {geom_identical}")
    print(f"  pair device-type span: random {med([v['span'] for v in R.values()]):.2f} "
          f"-> anticlustered {med([v['span'] for v in A.values()]):.2f}")
    print(f"  mean paired gain: margin {st.mean(dm):+.4f}, beta* {st.mean(db):+.4f} "
          f"({n_up} up / {n_dn} down / {len(seeds)-n_up-n_dn} unchanged)")


if __name__ == "__main__":
    main()
