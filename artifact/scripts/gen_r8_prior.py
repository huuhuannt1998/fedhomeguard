#!/usr/bin/env python3
"""Review r6 (B-W3): certified accuracy under a benign-majority prior.

The test split is attack-majority (tau_triv is the malicious rate), and a deployed
detector faces the opposite prior. Reweighting needs no new run: every row carries the
certified-and-correct rates per class, CTR_mal and CTR_ben, and

    CA = tau * CTR_mal + (1 - tau) * CTR_ben          (checked below, to 1e-6)

so the certified accuracy at attack prior pi is pi * CTR_mal + (1 - pi) * CTR_ben, to be
read against the floor 1 - pi of the constant benign predictor.

Reads the same-predictor rows (aggregate.src: corrected unless FHG_FROZEN=1) and writes
generated/prior_macros.tex.
"""
import os, statistics as st, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from aggregate import load, src

from _manuscript import GENERATED as OUT  # TMLR generated/ (FHG_GENERATED overrides)
PI = 0.01                      # attack prior; the floor is 1 - PI


def main():
    rows = load(src("e2_*.jsonl"))
    bad = [r for r in rows
           if abs(r["CA"] - (r["tau_triv"] * r["CTR_mal"] + (1 - r["tau_triv"]) * r["CTR_ben"])) > 1e-5]
    if bad:
        print(f"{len(bad)} rows do not decompose into CTR_mal and CTR_ben -- refusing"); return 1
    cells = {}
    for r in rows:
        cells.setdefault((r["partition_type"], r["k"], round(r["beta"], 4)), []).append(r)
    ca_pi = {kk: st.median([PI * r["CTR_mal"] + (1 - PI) * r["CTR_ben"] for r in v])
             for kk, v in cells.items()}
    above = sum(v > 1 - PI + 1e-12 for v in ca_pi.values())
    ref = ("iid", 1, 0.4)
    mac = dict(prPiPct=f"{100 * PI:g}", prFloor=f"{1 - PI:.4f}",
               prCAiid=f"{ca_pi[ref]:.4f}",
               prCTRmal=f"{st.median([r['CTR_mal'] for r in cells[ref]]):.4f}",
               prCells=str(len(ca_pi)), prCellsAbove=str(above),
               prCAmax=f"{max(ca_pi.values()):.4f}")
    for kk in sorted(ca_pi):
        print(f"  {kk}: CA at pi={PI:g} -> {ca_pi[kk]:.4f}")
    print(mac)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "prior_macros.tex"), "w") as fh:
        fh.write("% GENERATED by scripts/gen_r8_prior.py -- do not edit\n")
        for k, v in mac.items():
            fh.write("\\newcommand{\\%s}{%s}\n" % (k, v))
    print(f"wrote {OUT}/prior_macros.tex")
    return 0


if __name__ == "__main__":
    sys.exit(main())
