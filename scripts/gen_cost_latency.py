#!/usr/bin/env python3
"""Absolute inference cost and server-side state (review technical comment 7).

The cost table reports client-rounds, where k=1 is 1x FedAvg. That is the CLIENT's
ledger. The server holds K models rather than one and runs K forward passes, and
"20x inference" only means something with an absolute number attached.

Two numbers, because they differ by orders of magnitude and only one of them is
the deployment number: amortised throughput over a batch, and the latency of
scoring a single flow. Both on CPU, since an edge gateway has no accelerator --
and for this model CPU is FASTER per flow than the laptop's GPU, which is
kernel-launch bound at these sizes. Aggregation work is unchanged: the same
client updates are averaged, only partitioned across K members.
"""
import os, sys, time
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
import torch
from fedhomeguard import config as CFG, runner as R
from fedhomeguard.models import build_model

OUT = "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated"
BATCH, K1 = 1024, 20
cfg = CFG.load("configs/stage3_certification.yaml")
cfg.partition.kind = "device_derived"; cfg.partition.seed = 0
t = R.prepare(cfg, verbose=False)
X = t["Xte"].cpu()
net = build_model(cfg, X.shape[1]).eval()
P = sum(p.numel() for p in net.parameters())


def per_flow(b, reps=200):
    xb = X[:b]
    with torch.no_grad():
        for _ in range(20):
            net(xb)
        t0 = time.time()
        for _ in range(reps):
            net(xb)
        return (time.time() - t0) / reps / b


one, batched = per_flow(1), per_flow(BATCH)
mac = [f"\\newcommand{{\\costParams}}{{{P:,}}}".replace(",", "{,}"),
       f"\\newcommand{{\\costBatch}}{{{BATCH:,}}}".replace(",", "{,}"),
       f"\\newcommand{{\\costUsBatched}}{{{batched*K1*1e6:.2f}}}",
       f"\\newcommand{{\\costUsSingle}}{{{one*K1*1e6:.0f}}}",
       f"\\newcommand{{\\costFlowsPerSec}}{{{1.0/(one*K1)/1000:.1f}}}",
       f"\\newcommand{{\\costServerMB}}{{{P*K1*4/1e6:.2f}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/cost_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_cost_latency.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  {P} params/model, CPU")
print(f"  K={K1}: {batched*K1*1e6:.2f} us/flow batched({BATCH}), "
      f"{one*K1*1e6:.0f} us/flow one at a time "
      f"({1.0/(one*K1)/1000:.1f}k flows/s single-threaded)")
print(f"  server holds {P*K1:,} params = {P*K1*4/1e6:.2f} MB fp32")
