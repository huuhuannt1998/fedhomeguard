#!/usr/bin/env python3
"""F9 / review E1: the 30-draw companion to Table 2.

Table 2 reports the same-predictor grid from the e2_* arm: three partition draws
crossed with three malicious sets, nine numbers per cell, reported as a median with
no interval. The review's E1 asks what that median is worth. The answer is already
on disk and costs nothing to compute: e5f_{iid,device_derived}.jsonl hold THIRTY
partition draws per (k, beta) cell at k in {1,2}, fully enumerated, over the same
household population.

This generator does NOT restate Table 2 from the 30-draw arm, and deliberately so.
Table 2's numbers reach the paper through gate-checked macros, and silently
reassigning their source would change published values without a measurement to
justify the change. It emits a separate, clearly labelled table instead, and the
caption on each says which arm it is.

ONE HONEST LIMIT, stated in the caption rather than papered over: e5f was run
--clean-only, the certified arm alone, so it carries no attacked ensemble. EA and
therefore the slack G_cert exist in that file only at beta = 0, where they are
identically equal by construction. The 30-draw arm can put an interval on CA and on
coverage; it cannot put one on EA or on G. Reporting a range for those two would
mean inventing runs that were never made.

Reads : results/canonical/e5f_{iid,device_derived}.jsonl
Writes: generated/tab_gapspread.tex   (bare tabular; the float wrapper lives in
                                       generated/floats/)
        generated/gapspread_macros.tex
"""
import json, os, statistics as st, sys

OUT = "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated"
CANON = "results/canonical"
# Table 2's beta grid, so the two tables are read against each other row for row.
BETAS = [0.0, 0.05, 0.10, 0.20, 0.30, 0.40]
KS = [1, 2]


def load(part):
    rows = [json.loads(l) for l in open(f"{CANON}/e5f_{part}.jsonl") if l.strip()]
    out = {}
    for k in KS:
        for b in BETAS:
            cells = [r for r in rows if r["k"] == k and abs(r["beta"] - b) < 1e-9]
            if cells:
                out[(k, b)] = cells
    return out


def stat(cells, field):
    v = [c[field] for c in cells]
    return st.median(v), min(v), max(v), len(v)


def main():
    data = {p: load(p) for p in ("iid", "device_derived")}

    # Every cell must be the full 30 draws, or the "30-draw" claim in the caption is
    # false. Refuse to emit rather than print a smaller n under a caption saying 30.
    ndraw = set()
    for p, d in data.items():
        for key, cells in d.items():
            ndraw.add(len(cells))
            seeds = {c["partition_seed"] for c in cells}
            if len(seeds) != len(cells):
                sys.exit(f"FAIL {p} {key}: {len(cells)} rows over {len(seeds)} draws")
            if not all(c["full_enumeration"] for c in cells):
                sys.exit(f"FAIL {p} {key}: not fully enumerated")
    if len(ndraw) != 1:
        sys.exit(f"FAIL: cells hold differing draw counts {sorted(ndraw)}")
    N_DRAW = ndraw.pop()

    # Four columns, not six. The median is already in Table 2 from the other arm and
    # printing a second one invites exactly the "one number per quantity" complaint
    # the review makes elsewhere; what this table exists to add is the interval.
    lines = ["% GENERATED by scripts/gen_gapspread.py -- do not edit",
             r"\begin{tabular}{@{}l@{\;}l@{\;\;}c@{\;\;}c@{}}",
             r"\toprule",
             r"$k$ & $\beta$ & IID CA $[\min,\max]$ "
             r"& Device-derived CA $[\min,\max]$ \\",
             r"\midrule"]

    widths = {"iid": [], "device_derived": []}
    macros = []
    for k in KS:
        if k != KS[0]:
            lines.append(r"\midrule")
        for b in BETAS:
            cell = []
            for p in ("iid", "device_derived"):
                cells = data[p].get((k, b))
                if cells is None:
                    cell += [r"---"]
                    continue
                # A cell the geometry forbids has CA identically zero for every draw;
                # printing "0.0000 [0.0000,0.0000]" would read as a measurement of a
                # predictor rather than as an arithmetic impossibility. Table 2 marks
                # these void and so does this one.
                if not any(c["combinatorially_possible"] for c in cells):
                    cell += [r"\textit{void}"]
                    continue
                med, lo, hi, n = stat(cells, "CA")
                widths[p].append(hi - lo)
                cell += [f"[{lo:.4f}, {hi:.4f}]"]
                # No per-cell macro. A TeX control sequence cannot contain a digit,
                # so the obvious \SpCAIIDI20 naming does not compile, and the cells
                # are not cited individually in prose anyway -- the table carries
                # them and the headline widths below carry the reading.
            lines.append(f"{k} & {b:.2f} & " + " & ".join(cell) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    os.makedirs(OUT, exist_ok=True)
    with open(f"{OUT}/tab_gapspread.tex", "w") as fh:
        fh.write("\n".join(lines) + "\n")

    # Headline widths for the prose. The IID number is the point of the table: the
    # three-draw median of Table 2 is worth reporting because redrawing the partition
    # thirty times moves CA by less than this.
    wi, wd = max(widths["iid"]), max(widths["device_derived"])
    # widest device-derived cell, named, so the prose can say where the spread lives
    worst = max(((p, k, b, hi - lo)
                 for p in ("device_derived",) for k in KS for b in BETAS
                 if (k, b) in data[p] and any(c["combinatorially_possible"]
                                              for c in data[p][(k, b)])
                 for _, lo, hi in [stat(data[p][(k, b)], "CA")[:3]]),
                key=lambda t: t[3])
    macros += [
        f"\\newcommand{{\\SpDraws}}{{{N_DRAW}}}",
        f"\\newcommand{{\\SpWidthIID}}{{{wi:.4f}}}",
        f"\\newcommand{{\\SpWidthDev}}{{{wd:.4f}}}",
        f"\\newcommand{{\\SpWorstK}}{{{worst[1]}}}",
        f"\\newcommand{{\\SpWorstBeta}}{{{worst[2]:.2f}}}",
    ]
    with open(f"{OUT}/gapspread_macros.tex", "w") as fh:
        fh.write("% GENERATED by scripts/gen_gapspread.py -- do not edit\n"
                 + "\n".join(macros) + "\n")
    print(f"wrote tab_gapspread.tex, gapspread_macros.tex ({len(macros)} macros)")
    print(f"  {N_DRAW} draws per cell; widest CA range: IID {wi:.4f}, "
          f"device-derived {wd:.4f} (k={worst[1]}, beta={worst[2]:.2f})")


if __name__ == "__main__":
    main()
