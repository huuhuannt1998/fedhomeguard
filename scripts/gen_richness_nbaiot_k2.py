#!/usr/bin/env python3
"""N-BaIoT device-richness sweep at k=2 -> nbk2rich_macros.tex.

Completes the corpus x subsample 2x2. Predeclared in
predeclarations/richness_nbaiot_k2.md (commit 7f41a65) before the run:
  P1 flat (span <= 0.05), P2 at beta_geo(20,2)=0.250 every level, P3 no cell above.
Mirrors gen_richness_nbaiot.py (k=1) and gen_richness_k2.py (IoT-23, k=2);
the same bstar estimator, filtered to k == 2.
"""
import json, os, sys, statistics as st
sys.path.insert(0, os.path.dirname(__file__))
from bstar import bstar_per_draw

OUT = "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated"
CEIL = 0.250
NB = [("1", "e23_nbk2rich_1_1"), ("1--3", "e23_nbk2rich_1_3"), ("2--5", "e23_nbk2rich_2_5"),
      ("3--8", "e23_nbk2rich_3_8"), ("5--9", "e23_nbk2rich_5_9")]
IO = [("1", "e22_k2rich_1_1"), ("1--3", "e22_k2rich_1_3"), ("2--5", "e22_k2rich_2_5"),
      ("3--8", "e22_k2rich_3_8"), ("5--10", "e22_k2rich_5_10")]


def arm(stem):
    f = f"results/canonical/{stem}.jsonl"
    if not os.path.exists(f):
        return None
    rs = [x for x in (json.loads(l) for l in open(f) if l.startswith("{"))
          if x["partition_type"] == "device_derived" and x["k"] == 2]
    d = bstar_per_draw(rs)
    if not d:
        return None
    return dict(bstar=st.median(d.values()), n=len(d),
                lo=min(d.values()), hi=max(d.values()),
                sjs=st.median(x["S_JS"] for x in rs))


nb = {lab: arm(s) for lab, s in NB}
io = {lab: arm(s) for lab, s in IO}
missing = [lab for lab, a in nb.items() if a is None]
if missing:
    sys.exit(f"REFUSING to emit: N-BaIoT k=2 levels missing {missing}")

print("  N-BaIoT k=2 richness   (ceiling 0.250)")
print(f"    {'devices':<9}{'S_JS':>8}{'beta*':>8}{'min':>7}{'max':>7}{'draws':>7}")
for lab, a in nb.items():
    print(f"    {lab:<9}{a['sjs']:>8.3f}{a['bstar']:>8.3f}{a['lo']:>7.3f}{a['hi']:>7.3f}{a['n']:>7}")

nb_b = [a["bstar"] for a in nb.values()]
nb_span = max(nb_b) - min(nb_b)
io_b = [a["bstar"] for a in io.values() if a]
io_span = (max(io_b) - min(io_b)) if io_b else float("nan")
p1 = nb_span <= 0.05
p2 = all(abs(b - CEIL) < 1e-9 for b in nb_b)
p3 = max(a["hi"] for a in nb.values()) <= CEIL + 1e-9
print(f"  P1 span<=0.05: {nb_span:.3f} {'PASS' if p1 else 'FAIL'}   "
      f"P2 at ceiling: {'PASS' if p2 else 'FAIL'}   P3 no cell above: {'PASS' if p3 else 'FAIL'}")
print(f"  IoT-23 k=2 span for contrast: {io_span:.3f}")

mac = [f"\\newcommand{{\\nbkTwoSpan}}{{{nb_span:.3f}}}",
       f"\\newcommand{{\\nbkTwoMin}}{{{min(nb_b):.3f}}}",
       f"\\newcommand{{\\nbkTwoMax}}{{{max(nb_b):.3f}}}",
       f"\\newcommand{{\\nbkTwoLevels}}{{{len(nb)}}}",
       f"\\newcommand{{\\nbkTwoDraws}}{{{max(a['n'] for a in nb.values())}}}",
       f"\\newcommand{{\\nbkTwoOne}}{{{nb['1']['bstar']:.3f}}}",
       f"\\newcommand{{\\nbkTwoSjsOne}}{{{nb['1']['sjs']:.3f}}}",
       f"\\newcommand{{\\ioTwoSpan}}{{{io_span:.3f}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/nbk2rich_macros.tex", "w") as fh:
    fh.write("% generated by scripts/gen_richness_nbaiot_k2.py -- do not edit\n")
    fh.write("\n".join(mac) + "\n")
print(f"  wrote {OUT}/nbk2rich_macros.tex ({len(mac)} macros)")
