#!/usr/bin/env python3
"""Emit a docker-compose file for one federated run.

Households are separate containers with CPU and memory ceilings, so a household is a
constrained device rather than a thread. Compromised households differ from honest
ones only in entrypoint; the server is identical in every run and never told which
clients are hostile except for labelling the log it writes.
"""
from __future__ import annotations
import argparse, json, os


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, help="host path of the household shards")
    ap.add_argument("--out", default="docker/compose.generated.yml")
    ap.add_argument("--outdir", default="results/realstack")
    ap.add_argument("--N", type=int, default=20)
    ap.add_argument("--mal", type=int, nargs="*", default=[])
    ap.add_argument("--attack", default="sign_flip")
    ap.add_argument("--scale", type=float, default=1.0)
    ap.add_argument("--rounds", type=int, default=15)
    ap.add_argument("--tag", default="run")
    ap.add_argument("--cpus", default="0.4")
    ap.add_argument("--mem", default="300m")
    a = ap.parse_args()

    mal = sorted(set(a.mal))
    root, outdir = os.path.abspath(a.root), os.path.abspath(a.outdir)
    L = ["# GENERATED by scripts/gen_compose.py -- do not edit",
         "services:", "  server:", "    image: fedhomeguard-fl:latest",
         "    command: >",
         f"      python fl_server.py --rounds {a.rounds} --clients {a.N}",
         # emit --mal only when non-empty: an empty value makes the server's
         # argparse swallow the next flag as its argument and exit 2
         (f"      --mal {','.join(map(str, mal))} --out /out/{a.tag}.json"
          if mal else f"      --out /out/{a.tag}.json"),
         "    volumes:", f"      - {root}:/data:ro", f"      - {outdir}:/out",
         "    healthcheck:",
         '      test: ["CMD-SHELL", "python -c \'import socket;socket.create_connection((\\"127.0.0.1\\",8080),2)\'"]',
         "      interval: 2s", "      timeout: 2s", "      retries: 40"]
    for cid in range(a.N):
        hostile = cid in mal
        cmd = (f"python fl_client_malicious.py --cid {cid} --attack {a.attack} "
               f"--scale {a.scale} --n-mal {len(mal)} --N {a.N}") if hostile else \
              f"python fl_client.py --cid {cid}"
        L += [f"  household-{cid:02d}:", "    image: fedhomeguard-fl:latest",
              f"    command: {cmd}",
              "    depends_on:", "      server:", "        condition: service_healthy",
              "    environment:", "      - FL_SERVER=server:8080",
              "    volumes:", f"      - {root}:/data:ro",
              "    deploy:", "      resources:", "        limits:",
              f"          cpus: '{a.cpus}'", f"          memory: {a.mem}"]
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    os.makedirs(outdir, exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {a.out}: {a.N} households, {len(mal)} compromised "
          f"({a.attack}), {a.rounds} rounds")


if __name__ == "__main__":
    main()
