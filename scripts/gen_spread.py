#!/usr/bin/env python3
"""Malicious-set vs partition-draw spread macros (review comment 8).

The review calls this the most important caution in the paper for evaluation
practice. Its two numbers were hardcoded in body prose, below the four-decimal
threshold the literal gate scans for, so nothing tied them to the table.
"""
import os, re, sys

OUT = "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated"
rows = []
for ln in open(f"{OUT}/tab_malset.tex"):
    c = [x.strip() for x in ln.split("&")]
    if len(c) == 4 and re.match(r"^[\d.]+$", c[1]):
        try:
            rows.append((c[0], float(c[1]), float(c[2]), float(c[3].replace("\\\\", "").strip())))
        except ValueError:
            pass
dev = [r for r in rows if r[0].lower().startswith("dev")]
iid = [r for r in rows if r[0].upper().startswith("IID")]
mac = [f"\\newcommand{{\\spreadDevPart}}{{{max(r[3] for r in dev):.2f}}}",
       f"\\newcommand{{\\spreadDevMal}}{{{max(r[2] for r in dev):.2f}}}",
       f"\\newcommand{{\\spreadIidMax}}{{{max(max(r[2], r[3]) for r in iid):.4f}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/spread_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_spread.py -- do not edit\n" + "\n".join(mac) + "\n")
print(f"  device-derived: partition-draw spread up to {max(r[3] for r in dev):.2f}, "
      f"malicious-set up to {max(r[2] for r in dev):.2f}")
print(f"  IID: both within {max(max(r[2], r[3]) for r in iid):.4f}")
