#!/usr/bin/env python3
"""Sampled vs fully enumerated k=3 (review E7).

E7 asked for full enumeration at k=3. The arm already existed (e2k3full, K=1,140)
and the ceiling table already used it -- but the methods said k=3 was SAMPLED at
K=500, which is the arm the rest of the paper uses. Running the enumeration again
replicated the existing arm draw-for-draw and settled the discrepancy.

The comparison must be made on the beta grid the two arms SHARE. The K=500
same-predictor arm runs the coarse grid {0, .05, .10, .20, .30, .40}; the full
enumeration runs the fine grid to 0.50 in steps of 0.05, which includes 0.15 =
beta_geo(20,3). Comparing raw beta* values therefore reported "understates on
3/3 draws, IID too", which was a grid artifact: the sample cannot express 0.15.
Restricting the full enumeration to the sampled arm's grid gives the honest
count, and the fine-grid ceiling attainment is reported separately.
"""
import glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bstar import bstar_per_draw
from aggregate import src as _src   # review r6: corrected same-predictor rows

OUT = os.environ.get("FHG_GENERATED",
                     "manuscripts/prj-01m0ee73rtcak0jngd4sy4a1y2/IEEE-SP/generated")


def load(pat, part, k=3):
    r = []
    for f in glob.glob(pat):
        r += [x for x in (json.loads(l) for l in open(f) if l.startswith("{"))
              if x["partition_type"] == part and x["k"] == k]
    return r


out = {}
BETA_GEO_K3 = 0.15  # beta_geo(20,3) = max{m/20 : C(20-m,3)/C(20,3) > 1/2}
for part, tag in (("device_derived", "Dev"), ("iid", "Iid")):
    samp_rows = load(_src("e2_%s_*.jsonl" % part), part)
    full_rows = load("results/canonical/e2k3full_%s_*.jsonl" % part, part)
    grid = {round(x["beta"], 6) for x in samp_rows}
    samp = bstar_per_draw(samp_rows)
    full_common = bstar_per_draw([x for x in full_rows if round(x["beta"], 6) in grid])
    full = bstar_per_draw(full_rows)
    rep = bstar_per_draw(load("results/canonical/e20_k3full_%s.jsonl" % part, part))
    seeds = sorted(set(samp) & set(full_common))
    under = sum(1 for s in seeds if samp[s] < full_common[s] - 1e-9)
    over = sum(1 for s in seeds if samp[s] > full_common[s] + 1e-9)
    agree = sum(1 for s in sorted(set(full) & set(rep)) if abs(full[s] - rep[s]) < 1e-9)
    ceil = sum(1 for s in full if abs(full[s] - BETA_GEO_K3) < 1e-9)
    out[tag] = (under, len(seeds), agree, len(set(full) & set(rep)), over, ceil, len(full))
    print(f"  {part}: on the shared grid the K=500 sample understates beta* on "
          f"{under}/{len(seeds)} draws and overstates on {over}; full enumeration "
          f"reaches beta_geo on {ceil}/{len(full)} draws; replication agrees on "
          f"{agree}/{len(set(full) & set(rep))}")

mac = [f"\\newcommand{{\\kThreeTotal}}{{1{{,}}140}}",
       f"\\newcommand{{\\kThreeSampled}}{{500}}",
       f"\\newcommand{{\\kThreeUnderDev}}{{{out['Dev'][0]}}}",
       f"\\newcommand{{\\kThreeDrawsDev}}{{{out['Dev'][1]}}}",
       f"\\newcommand{{\\kThreeUnderIid}}{{{out['Iid'][0]}}}",
       f"\\newcommand{{\\kThreeDrawsIid}}{{{out['Iid'][1]}}}",
       f"\\newcommand{{\\kThreeRepAgree}}{{{out['Dev'][2] + out['Iid'][2]}}}",
       f"\\newcommand{{\\kThreeRepTotal}}{{{out['Dev'][3] + out['Iid'][3]}}}",
       f"\\newcommand{{\\kThreeOverAny}}{{{out['Dev'][4] + out['Iid'][4]}}}",
       f"\\newcommand{{\\kThreeCeilDev}}{{{out['Dev'][5]}}}",
       f"\\newcommand{{\\kThreeCeilIid}}{{{out['Iid'][5]}}}",
       f"\\newcommand{{\\kThreeFullDraws}}{{{out['Dev'][6]}}}"]
os.makedirs(OUT, exist_ok=True)
with open(f"{OUT}/k3_macros.tex", "w") as fh:
    fh.write("% GENERATED by scripts/gen_k3.py -- do not edit\n" + "\n".join(mac) + "\n")
